import { useEffect, useState } from 'react'
import { Bip39, TenshuSdk } from '@tenshu/sdk/core'
import { demoDevice, type Device } from '@tenshu/sdk/identity'
import { Notifications, type Notification } from '@tenshu/sdk/notifications'
import {
  Files,
  Folders,
  type File,
  type Folder,
} from '@tenshu/sdk/files'
import { bytesToHex, formatBytes } from '../lib/format'

// SDK exploration / smoke-test surface. Useful for manually exercising the
// schema walker and stream plumbing during development; not user-facing.
// Once vitest + RTL is in place (Phase T) the walker assertions move into
// real unit tests and most of this page goes away.
export default function DevPage() {
  const [mnemonic, setMnemonic] = useState<string | null>(null)
  const [device, setDevice] = useState<Device | null>(null)
  const [notification, setNotification] = useState<Notification | null>(null)
  const [file, setFile] = useState<File | null>(null)
  const [folder, setFolder] = useState<Folder | null>(null)
  const [runtimeStatus] = useState(() => TenshuSdk.runtimeStatus())
  const [liveNotifications, setLiveNotifications] = useState<readonly Notification[]>([])
  useEffect(() => Notifications.observe(items => setLiveNotifications(items)), [])
  return (
    <div>
      <h1 className="text-2xl font-medium">SDK dev surface</h1>
      <p className="mt-1 text-sm text-text-2">
        Manual smoke tests for the JS SDK. Schema walker, BIP-39, live
        notification stream — moves into vitest once Phase T lands.
      </p>
      <p className="mt-2 text-sm text-text-2">
        Runtime: <code className="font-mono">{runtimeStatus.ready ? 'ready' : 'not ready'}</code>{' '}
        · clock <code className="font-mono">{new Date(runtimeStatus.nowMs).toISOString()}</code>
      </p>
      <section className="mt-8">
        <h2 className="text-xl font-medium">BIP-39 mnemonic</h2>
        <p className="mt-1 text-sm text-text-2">
          Generated by the shared Kotlin <code className="font-mono">Bip39.generateMnemonic()</code>.
        </p>
        <button
          type="button"
          onClick={() => setMnemonic(Bip39.generateMnemonic())}
          className="mt-4 rounded-md bg-primary px-4 py-2 text-sm font-medium text-on-primary hover:bg-primary/90"
        >
          Generate
        </button>
        {mnemonic !== null && (
          <p className="mt-4 break-words font-mono text-sm">{mnemonic}</p>
        )}
      </section>
      <section className="mt-8">
        <h2 className="text-xl font-medium">Device snapshot</h2>
        <p className="mt-1 text-sm text-text-2">
          A <code className="font-mono">Device</code> Composite, walked through the schema and
          flattened to a plain JS object.
        </p>
        <button
          type="button"
          onClick={() => setDevice(demoDevice())}
          className="mt-4 rounded-md bg-primary px-4 py-2 text-sm font-medium text-on-primary hover:bg-primary/90"
        >
          Load demo device
        </button>
        {device !== null && (
          <dl className="mt-4 grid grid-cols-[max-content_1fr] gap-x-4 gap-y-1 text-sm">
            <dt className="font-mono text-text-2">deviceId</dt>
            <dd className="font-mono">{device.deviceId}</dd>
            <dt className="font-mono text-text-2">name</dt>
            <dd className="font-mono">{device.name}</dd>
            <dt className="font-mono text-text-2">publicKey</dt>
            <dd className="break-all font-mono">{bytesToHex(device.publicKey)}</dd>
            <dt className="font-mono text-text-2">isCurrent</dt>
            <dd className="font-mono">{String(device.isCurrent)}</dd>
            <dt className="font-mono text-text-2">isAuthorized</dt>
            <dd className="font-mono">{String(device.isAuthorized)}</dd>
          </dl>
        )}
      </section>
      <section className="mt-8">
        <h2 className="text-xl font-medium">Notification snapshot</h2>
        <p className="mt-1 text-sm text-text-2">
          Exercises the <code className="font-mono">UnixInstant</code> unwrap path
          (TInteger leaf → JS <code className="font-mono">number</code> in epoch ms).
        </p>
        <button
          type="button"
          onClick={() => setNotification(Notifications.demo())}
          className="mt-4 rounded-md bg-primary px-4 py-2 text-sm font-medium text-on-primary hover:bg-primary/90"
        >
          Load demo notification
        </button>
        {notification !== null && (
          <dl className="mt-4 grid grid-cols-[max-content_1fr] gap-x-4 gap-y-1 text-sm">
            <dt className="font-mono text-text-2">uuid</dt>
            <dd className="font-mono">{notification.uuid}</dd>
            <dt className="font-mono text-text-2">timestamp</dt>
            <dd className="font-mono">
              {notification.timestamp}{' '}
              <span className="text-text-2">
                ({new Date(notification.timestamp).toISOString()})
              </span>
            </dd>
          </dl>
        )}
      </section>
      <section className="mt-8">
        <h2 className="text-xl font-medium">File snapshot</h2>
        <p className="mt-1 text-sm text-text-2">
          Adds the <code className="font-mono">TInteger</code> branch to the walker
          (<code className="font-mono">size</code> → JS number).
        </p>
        <button
          type="button"
          onClick={() => setFile(Files.demo())}
          className="mt-4 rounded-md bg-primary px-4 py-2 text-sm font-medium text-on-primary hover:bg-primary/90"
        >
          Load demo file
        </button>
        {file !== null && (
          <dl className="mt-4 grid grid-cols-[max-content_1fr] gap-x-4 gap-y-1 text-sm">
            <dt className="font-mono text-text-2">path</dt>
            <dd className="font-mono">{file.path}</dd>
            <dt className="font-mono text-text-2">size</dt>
            <dd className="font-mono">{formatBytes(file.size)}</dd>
            <dt className="font-mono text-text-2">lastModified</dt>
            <dd className="font-mono">
              {new Date(file.lastModified).toISOString()}
            </dd>
          </dl>
        )}
      </section>
      <section className="mt-8">
        <h2 className="text-xl font-medium">Folder snapshot</h2>
        <p className="mt-1 text-sm text-text-2">
          Exercises the <code className="font-mono">TList&lt;File&gt;</code> walker branch
          and parent-schema field inheritance — Folder extends File, so{' '}
          <code className="font-mono">path</code>/<code className="font-mono">size</code>/
          <code className="font-mono">lastModified</code> come along inherited.
        </p>
        <button
          type="button"
          onClick={() => setFolder(Folders.demo())}
          className="mt-4 rounded-md bg-primary px-4 py-2 text-sm font-medium text-on-primary hover:bg-primary/90"
        >
          Load demo folder
        </button>
        {folder !== null && (
          <div className="mt-4">
            <p className="text-sm">
              <span className="font-mono text-text-2">path: </span>
              <span className="font-mono">{folder.path}</span>
            </p>
            <ul className="mt-2 divide-y border-t border-b">
              {folder.files.map((f, i) => (
                <li key={i} className="grid grid-cols-[1fr_max-content_max-content] gap-4 py-2 text-sm">
                  <span className="font-mono">{f.path}</span>
                  <span className="font-mono text-text-2">{formatBytes(f.size)}</span>
                  <span className="font-mono text-text-2">
                    {new Date(f.lastModified).toISOString().slice(0, 10)}
                  </span>
                </li>
              ))}
            </ul>
          </div>
        )}
      </section>
      <section className="mt-8">
        <h2 className="text-xl font-medium">Notifications.observe (live stream)</h2>
        <p className="mt-1 text-sm text-text-2">
          Stream dispatch through{' '}
          <code className="font-mono">JsRuntime.tenshuClient.notificationService</code> →{' '}
          <code className="font-mono">flow().collect</code>. Each emission delivers the
          full snapshot. The apex's seed folder creations should naturally produce
          <code className="font-mono"> FolderAddedNotification</code>s.
        </p>
        <p className="mt-2 text-xs text-text-2">
          live count: <code className="font-mono">{liveNotifications.length}</code>
        </p>
        <ul className="mt-2 divide-y border-t border-b">
          {liveNotifications.map(n => (
            <li key={n.uuid} className="grid grid-cols-[1fr_max-content] gap-4 py-2 text-sm">
              <span className="font-mono">{n.uuid}</span>
              <span className="font-mono text-text-2">
                {new Date(n.timestamp).toISOString().slice(11, 19)}
              </span>
            </li>
          ))}
        </ul>
      </section>
    </div>
  )
}
