// 3-of-24 confirm widget for UX §4b.4. The parent generates the random
// positions once (re-displaying the phrase resets the widget by
// remounting); each labelled input uses `WordlistInput` for autocomplete.
import { useState } from 'react'
import { useTranslation } from 'react-i18next'
import { WordlistInput } from './WordlistInput'
import { LinkButton, PrimaryButton } from '../OnboardingShell'

export interface MnemonicConfirmProps {
  readonly mnemonic: readonly string[]
  readonly positions: readonly number[]
  readonly onConfirmed: () => void
  readonly onRedisplay: () => void
}

export function MnemonicConfirm({
  mnemonic,
  positions,
  onConfirmed,
  onRedisplay,
}: MnemonicConfirmProps) {
  const { t } = useTranslation('onboarding')
  // `positions` is generated by the parent on mount and never changes for
  // the lifetime of this component — the parent re-mounts (via key) when
  // the user re-displays the phrase. So `useState`'s initial-from-prop
  // pattern is correct here without a sync effect.
  const [values, setValues] = useState<readonly string[]>(() => positions.map(() => ''))
  const [attemptCount, setAttemptCount] = useState(0)
  const [error, setError] = useState<string | null>(null)

  function setAt(idx: number, next: string): void {
    setValues(prev => prev.map((v, i) => (i === idx ? next : v)))
    setError(null)
  }

  const allFilled = values.every(v => v.trim() !== '')

  function onVerify() {
    const ok = positions.every((pos, i) => {
      const expected = mnemonic[pos]
      return values[i]?.trim().toLowerCase() === expected
    })
    if (ok) {
      onConfirmed()
      return
    }
    const next = attemptCount + 1
    setAttemptCount(next)
    setError(
      next >= 3
        ? t('newUser.confirm.errorTooManyMisses')
        : t('newUser.confirm.errorMismatch'),
    )
  }

  const requireRedisplay = attemptCount >= 3

  return (
    <div>
      <ol className="grid grid-cols-1 gap-4 sm:grid-cols-3">
        {positions.map((pos, idx) => (
          <li key={pos}>
            <WordlistInput
              label={t('newUser.confirm.wordLabel', { position: pos + 1 })}
              value={values[idx] ?? ''}
              autoFocus={idx === 0}
              onChange={next => setAt(idx, next)}
              placeholder={t('newUser.confirm.wordPlaceholder')}
            />
          </li>
        ))}
      </ol>
      {error !== null && (
        <p
          role="alert"
          className="mt-4 rounded-md border border-danger/30 bg-danger/10 px-3 py-2 text-sm text-danger"
        >
          {error}
        </p>
      )}
      <div className="mt-6 flex flex-wrap items-center gap-3">
        <PrimaryButton onClick={onVerify} disabled={!allFilled || requireRedisplay}>
          {t('newUser.confirm.verify')}
        </PrimaryButton>
        <LinkButton onClick={onRedisplay}>{t('newUser.confirm.redisplay')}</LinkButton>
      </div>
    </div>
  )
}
