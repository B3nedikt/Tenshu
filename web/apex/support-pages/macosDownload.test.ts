// @vitest-environment node
//
// The macOS download pages and the casks' livecheck files (macosDownload.ts;
// desktop-macos-distribution.md §2.12.6 H7). Pins: rendered from the committed
// store/macos-release.json at build time, "not available yet" (no link, no macos.json) without it, a
// malformed file fails the build, and the guide says what the decisions require (Control first,
// Apple silicon + macOS 14, Homebrew line, one copy per app, how to check the download).
//
// ⚠ Every build here uses its own temporary store directory, so these tests do not change meaning
// with each release the publish step commits.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { APEX_DIR, buildSupportSite } from './generate.ts'
import { loadSupportChrome } from './loadChrome.ts'
import { MACOS_APPS, MACOS_DOWNLOAD, MACOS_RELEASE_FILE, MACOS_TEAM_ID, loadMacosRelease } from './macosDownload.ts'

const chrome = await loadSupportChrome('test')

const HEX = (c: string) => c.repeat(64)
const BASE = 'https://releases.tenshu.app/sha256/'
const NAME = (app: string) => `Tenshu${app[0]!.toUpperCase()}${app.slice(1)}`
// The shape scripts/lib/macos_publish.py writes (docs/how-to/macos-release.md §7, schema 1).
const release = (apps: Record<string, unknown>, extra: Record<string, unknown> = {}) => ({
  about: 'Generated by scripts/macos-direct-publish.sh — do not edit.',
  schema: 1,
  base: BASE,
  version: '1.0.1',
  build: '202611061517',
  minimumMacOS: '14.0',
  arch: 'arm64',
  teamId: MACOS_TEAM_ID,
  published: '2026-11-06',
  apps,
  ...extra,
})
const entry = (app: string, c = 'a', bytes = 141_885_057) => ({
  bundle: NAME(app),
  bundleId: `app.tenshu.${app}.ios`,
  file: `${NAME(app)}-1.0.1.dmg`,
  url: `${BASE}${HEX(c)}.dmg`,
  sha256: HEX(c),
  bytes,
})

async function withRelease<T>(content: unknown | undefined, run: (dir: string) => Promise<T> | T): Promise<T> {
  const dir = mkdtempSync(join(tmpdir(), 'macos-release-'))
  try {
    if (content !== undefined) writeFileSync(join(dir, MACOS_RELEASE_FILE), typeof content === 'string' ? content : JSON.stringify(content))
    return await run(dir)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

const fileOf = (files: readonly { file: string; content: string }[], name: string) => {
  const f = files.find((x) => x.file === name)
  if (!f) throw new Error(`no ${name}`)
  return f.content
}
const article = (html: string) => html.slice(html.indexOf('<article'), html.indexOf('</article>'))

describe('macOS download pages', () => {
  it('without a release file: every app and language is built, says "not available yet", links no .dmg and writes no macos.json', async () => {
    const site = await withRelease(undefined, (dir) => buildSupportSite({ chrome, storeDir: dir }))
    for (const app of MACOS_APPS) {
      for (const lang of ['en', 'de', 'fr']) {
        const html = fileOf(site.files, `apps/${app}/download/macos/${lang}/index.html`)
        const body = article(html)
        expect(html, `${app} ${lang}`).toContain(`<link rel="canonical" href="https://tenshu.app/apps/${app}/download/macos/${lang}">`)
        expect(html).toContain(`<link rel="alternate" hreflang="x-default" href="https://tenshu.app/apps/${app}/download/macos">`)
        expect(body, `${app} ${lang}`).toContain(`data-dmg-unavailable="${app}"`)
        expect(body).toContain(MACOS_DOWNLOAD[lang]!.notYet)
        expect(body).not.toMatch(/\.dmg"|data-dmg="/)
        // No cask exists for an unpublished app, and there is no checksum to compare with.
        expect(body).not.toContain('brew install --cask')
        expect(body).not.toContain('shasum')
        expect(body).toContain('data-homebrew-unavailable')
      }
      expect(site.files.some((f) => f.file === `apps/${app}/download/macos.json`), app).toBe(false)
    }
  })

  it('with a release: the button links the published URL with version, size and hash; macos.json carries the same', async () => {
    const site = await withRelease(release({ control: entry('control'), photos: entry('photos', 'b', 9_000_000) }), (dir) => buildSupportSite({ chrome, storeDir: dir }))
    const control = article(fileOf(site.files, 'apps/control/download/macos/en/index.html'))
    expect(control).toContain(`href="${BASE}${HEX('a')}.dmg"`)
    expect(control).toContain('Version 1.0.1 · 142 MB · Mac with Apple silicon, macOS 14 or later')
    expect(control).toContain(HEX('a'))
    expect(control).toContain('brew install --cask b3nedikt/tenshu/tenshu-control')
    expect(article(fileOf(site.files, 'apps/photos/download/macos/de/index.html'))).toContain('Version 1.0.1 · 9,0 MB')
    // The livecheck file: exactly what the cask needs, and only for apps the release carries.
    expect(JSON.parse(fileOf(site.files, 'apps/photos/download/macos.json'))).toEqual({
      version: '1.0.1', build: '202611061517', url: `${BASE}${HEX('b')}.dmg`, sha256: HEX('b'),
    })
    expect(site.files.some((f) => f.file === 'apps/maps/download/macos.json')).toBe(false)
    const maps = article(fileOf(site.files, 'apps/maps/download/macos/en/index.html'))
    expect(maps).toContain('data-dmg-unavailable="maps"')
    expect(maps).toContain('<a href="/apps/control/download/macos/en">Tenshu Control</a> · 142 MB')
    expect(maps).toContain('<strong>Tenshu Maps</strong> · not available yet')
  })

  it('the guide: Control first, Homebrew, one copy per app, Apple silicon only, and how to check the signer', async () => {
    const site = await withRelease(release({ control: entry('control'), drive: entry('drive') }), (dir) => buildSupportSite({ chrome, storeDir: dir }))
    for (const lang of ['en', 'de', 'fr']) {
      const drive = article(fileOf(site.files, `apps/drive/download/macos/${lang}/index.html`))
      const control = article(fileOf(site.files, `apps/control/download/macos/${lang}/index.html`))
      // The sentence itself: the all-apps list links Control on every page, so the href alone proves nothing.
      expect(drive, lang).toContain(MACOS_DOWNLOAD[lang]!.controlFirst(`/apps/control/download/macos/${lang}`))
      expect(control, lang).not.toContain(MACOS_DOWNLOAD[lang]!.controlFirst(`/apps/control/download/macos/${lang}`))
      // Updating by hand: quit first (Control's tray keeps it running otherwise).
      expect(drive, lang).toContain('<code>brew upgrade --cask</code>')
      for (const id of ['install', 'homebrew', 'update', 'mac-app-store', 'verify', 'requirements', 'all-apps']) expect(drive, `${lang} #${id}`).toContain(`<h2 id="${id}">`)
      expect(drive, lang).toContain('brew install --cask b3nedikt/tenshu/tenshu-drive')
      expect(drive, lang).toContain('brew install --cask b3nedikt/tenshu/tenshu-control')
      expect(drive, lang).toContain('source=Notarized Developer ID')
      expect(drive, lang).toContain(`(${MACOS_TEAM_ID})`)
      expect(drive, lang).toContain('M1')
      expect(drive, lang).not.toContain('—')
    }
    expect(Object.fromEntries(Object.entries(MACOS_DOWNLOAD).map(([l, p]) => [l, p.reviewed]))).toEqual({ en: true, de: false, fr: false })
  })

  it('lists the catalogue apps in catalogue order (scripts/lib/app-catalogue.sh TENSHU_APP_KEYS)', () => {
    const sh = readFileSync(join(APEX_DIR, '..', '..', 'scripts', 'lib', 'app-catalogue.sh'), 'utf8')
    const keys = /^TENSHU_APP_KEYS="([^"]*)"/m.exec(sh)
    expect(keys, 'TENSHU_APP_KEYS in app-catalogue.sh').not.toBeNull()
    expect([...MACOS_APPS]).toEqual(keys![1]!.split(' '))
  })

  it('the app pages offer Mac through this page', async () => {
    const site = await withRelease(release({ control: entry('control') }), (dir) => buildSupportSite({ chrome, storeDir: dir }))
    expect(fileOf(site.files, 'apps/photos/en/index.html')).toContain('href="/apps/photos/download/macos"')
  })

  it('a malformed release fails the build rather than publishing a wrong link', async () => {
    const bad: [unknown, RegExp][] = [
      ['{ nope', /not JSON/],
      [release({}, { schema: 2 }), /schema must be 1/],
      [release({}, { base: 'https://releases.tenshu.app/' }), /base must be/],
      [release({}, { arch: 'x86_64' }), /arch must be arm64/],
      [release({}, { teamId: 'FAYT82GWD7' }), /teamId/],
      [release({}, { build: '1' }), /build must be/],
      [release({}, { minimumMacOS: '14' }), /minimumMacOS/],
      [release({ chess: entry('chess') }), /unknown app "chess"/],
      [release({ drive: { ...entry('drive'), bundleId: 'app.tenshu.drive' } }), /apps\.drive: bundleId/],
      [release({ drive: { ...entry('drive'), url: `${BASE}${HEX('b')}.dmg` } }), /apps\.drive: url must be base/],
      [release({ drive: { ...entry('drive'), file: 'TenshuDrive-1.0.0.dmg' } }), /apps\.drive: file/],
      [release({ drive: { ...entry('drive'), bytes: 0 } }), /apps\.drive: bytes/],
    ]
    for (const [content, error] of bad) {
      await withRelease(content, (dir) => expect(() => loadMacosRelease(dir), String(error)).toThrow(error))
    }
    await withRelease('{ nope', (dir) => expect(buildSupportSite({ chrome, storeDir: dir })).rejects.toThrow(/macos-release\.json: not JSON/))
  })

  it('accepts the minimum macOS forms the publish step writes (x.y and x.y.z)', async () => {
    await withRelease(release({ control: entry('control') }, { minimumMacOS: '14.0.1' }), (dir) => expect(loadMacosRelease(dir)?.minimumMacOS).toBe('14.0.1'))
  })

  it('the committed release (store/macos-release.json) loads', () => {
    const r = loadMacosRelease(join(APEX_DIR, '..', '..', 'store'))
    expect(r?.apps.control?.url).toMatch(/^https:\/\/releases\.tenshu\.app\/sha256\/[0-9a-f]{64}\.dmg$/)
  })
})
