// @vitest-environment node
//
// The Android download pages (androidDownload.ts; android-direct-apk-distribution.md Phase 1 item 5).
// Pins the promises the page makes: rendered from the committed store/android-release.json at build
// time, "not available yet" (and no APK link) without it, a malformed file fails the build, and the
// install guide says what the decisions require (Control first, update by downloading again, arm64
// only, never mix with Google Play, apksigner against the published fingerprint).
//
// ⚠ Every build here uses its own temporary store directory: the real store/ gains the release file
// when the publish step first runs, and these tests must not change meaning on that day.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { APEX_DIR, buildSupportSite } from './generate.ts'
import { loadSupportChrome } from './loadChrome.ts'
import { ANDROID_APPS, ANDROID_DOWNLOAD, ANDROID_RELEASE_FILE, apksignerDigest, loadAndroidRelease } from './androidDownload.ts'

const chrome = await loadSupportChrome('test')

const CERT = Array.from({ length: 32 }, (_, i) => (i * 7 + 16).toString(16).toUpperCase().padStart(2, '0')).join(':')
const HEX = (c: string) => c.repeat(64)
const BASE = 'https://releases.tenshu.app/sha256/'
// The shape scripts/lib/direct_publish.py writes (docs/how-to/android-release.md, schema 1).
const release = (apps: Record<string, unknown>, extra: Record<string, unknown> = {}) => ({
  about: 'Generated by scripts/android-direct-publish.sh — do not edit.',
  schema: 1,
  base: BASE,
  abi: 'arm64-v8a',
  signingCertSha256: CERT,
  apps,
  ...extra,
})
const entry = (app: string, c = 'a', bytes = 35_400_000, versionCode = 6) => ({
  package: `app.tenshu.${app}.android`,
  versionCode,
  versionName: '1.0.2',
  abi: 'arm64-v8a',
  signingCertSha256: CERT,
  sha256: HEX(c),
  bytes,
  filename: `tenshu-${app}-${versionCode}.apk`,
  url: `${BASE}${HEX(c)}.apk`,
  published: '2026-11-04',
})

async function withRelease<T>(content: unknown | undefined, run: (dir: string) => Promise<T> | T): Promise<T> {
  const dir = mkdtempSync(join(tmpdir(), 'android-release-'))
  try {
    if (content !== undefined) writeFileSync(join(dir, ANDROID_RELEASE_FILE), typeof content === 'string' ? content : JSON.stringify(content))
    return await run(dir)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

const fileOf = (files: readonly { file: string; content: string }[], name: string) => {
  const f = files.find((x) => x.file === name)
  if (!f) throw new Error(`no ${name}`)
  return f.content
}
const article = (html: string) => html.slice(html.indexOf('<article'), html.indexOf('</article>'))

describe('Android download pages', () => {
  it('without a release file: every app and language is built, says "not available yet" and links no APK', async () => {
    const site = await withRelease(undefined, (dir) => buildSupportSite({ chrome, storeDir: dir }))
    for (const app of ANDROID_APPS) {
      for (const lang of ['en', 'de', 'fr']) {
        const html = fileOf(site.files, `apps/${app}/download/android/${lang}/index.html`)
        const body = article(html)
        expect(html, `${app} ${lang}`).toContain(`<link rel="canonical" href="https://tenshu.app/apps/${app}/download/android/${lang}">`)
        expect(html).toContain(`<link rel="alternate" hreflang="x-default" href="https://tenshu.app/apps/${app}/download/android">`)
        expect(body, `${app} ${lang}`).toContain(`data-apk-unavailable="${app}"`)
        expect(body).toContain(ANDROID_DOWNLOAD[lang]!.notYet)
        expect(body).not.toMatch(/\.apk"|data-apk="/)
        expect(body).not.toContain('data-cert')
      }
      // The language-neutral URL's static list (what a host without the Caddy 302 serves).
      expect(fileOf(site.files, `apps/${app}/download/android/index.html`)).toContain(`<a href="/apps/${app}/download/android/en" hreflang="en" lang="en">`)
    }
  })

  it('with a release: the button links the published URL, with size, version, file hash and the signing fingerprint', async () => {
    const site = await withRelease(release({ control: entry('control'), drive: entry('drive', 'b', 9_000_000, 7) }), (dir) => buildSupportSite({ chrome, storeDir: dir }))
    const control = article(fileOf(site.files, 'apps/control/download/android/en/index.html'))
    expect(control).toContain(`href="${BASE}${HEX('a')}.apk"`)
    expect(control).toContain('Version 1.0.2 (6) · 35 MB · 64-bit ARM phones only')
    expect(control).toContain(HEX('a'))
    expect(control).toContain(`data-cert>${CERT}</code>`)
    expect(control).toContain('apksigner verify --print-certs tenshu-control-6.apk')
    expect(control).toContain(apksignerDigest(CERT))
    expect(apksignerDigest(CERT)).toMatch(/^[0-9a-f]{64}$/)
    // Each app shows its own version (publishing one app leaves the others' entries as they were),
    // and German writes the decimal comma.
    expect(article(fileOf(site.files, 'apps/drive/download/android/de/index.html'))).toContain('Version 1.0.2 (7) · 9,0 MB')
    // An app the release does not carry still says "not yet", on its own page and in every list.
    const maps = article(fileOf(site.files, 'apps/maps/download/android/en/index.html'))
    expect(maps).toContain('data-apk-unavailable="maps"')
    expect(maps).toContain('<a href="/apps/control/download/android/en">Tenshu Control</a> · 35 MB')
    expect(maps).toContain('<strong>Tenshu Maps</strong> · not available yet')
  })

  it('the guide: Control first, update by downloading again, never mix with Google Play, arm64 only', async () => {
    const site = await withRelease(release({ control: entry('control'), drive: entry('drive') }), (dir) => buildSupportSite({ chrome, storeDir: dir }))
    for (const lang of ['en', 'de', 'fr']) {
      const drive = article(fileOf(site.files, `apps/drive/download/android/${lang}/index.html`))
      const control = article(fileOf(site.files, `apps/control/download/android/${lang}/index.html`))
      // Every non-Control page sends the reader to Control's first; Control's own page does not link itself.
      expect(drive, lang).toContain(`href="/apps/control/download/android/${lang}"`)
      expect(control.indexOf(`href="/apps/control/download/android/${lang}"`), lang).toBe(-1)
      for (const id of ['install', 'update', 'google-play', 'verify', 'requirements', 'all-apps']) expect(drive, `${lang} #${id}`).toContain(`<h2 id="${id}">`)
      expect(drive, lang).toContain('arm64-v8a')
      expect(drive, lang).toContain('Play Protect')
      expect(drive, lang).toContain(`href="/pricing/${lang}"`)
      // D4: no updater. The page must never promise one, nor link Google Play (Phase 1 item 10).
      expect(drive, lang).not.toContain('play.google.com')
      expect(drive, lang).not.toMatch(/F-Droid/i)
      expect(drive, lang).not.toContain('—')
    }
    expect(article(fileOf(site.files, 'apps/drive/download/android/en/index.html'))).toContain('download the latest APK and install it over the app you have')
    expect(Object.fromEntries(Object.entries(ANDROID_DOWNLOAD).map(([l, p]) => [l, p.reviewed]))).toEqual({ en: true, de: false, fr: false })
  })

  // The publish step's app list is what can appear in the file; an app it may publish that this list
  // lacks would fail the website build ("unknown app"). Read from the script, not copied.
  it('knows every app the publish step may write (scripts/lib/direct_publish.py APPS)', () => {
    const py = readFileSync(join(APEX_DIR, '..', '..', 'scripts', 'lib', 'direct_publish.py'), 'utf8')
    const tuple = /^APPS = \(([^)]*)\)/m.exec(py)
    expect(tuple, 'APPS = (...) in direct_publish.py').not.toBeNull()
    const apps = [...tuple![1]!.matchAll(/"([a-z]+)"/g)].map((m) => m[1]!)
    expect([...apps].sort()).toEqual([...ANDROID_APPS].sort())
  })

  it('a malformed release fails the build rather than publishing a wrong link or fingerprint', async () => {
    const bad: [unknown, RegExp][] = [
      ['{ nope', /not JSON/],
      [release({}, { schema: 2 }), /schema must be 1/],
      [release({}, { base: 'http://releases.tenshu.app/sha256/' }), /base must be an https URL/],
      [release({}, { abi: 'armeabi-v7a' }), /abi must be arm64-v8a/],
      [release({}, { signingCertSha256: CERT.toLowerCase() }), /signingCertSha256/],
      [release({ chess: entry('chess') }), /unknown app "chess"/],
      [release({ drive: { ...entry('drive'), package: 'app.tenshu.control.android' } }), /apps\.drive: package/],
      [release({ drive: { ...entry('drive'), url: 'https://elsewhere.example/x.apk' } }), /apps\.drive: url must be base/],
      [release({ drive: { ...entry('drive'), url: `${BASE}${HEX('b')}.apk` } }), /apps\.drive: url must be base/],
      [release({ drive: { ...entry('drive'), signingCertSha256: CERT.replace('10', '11') } }), /apps\.drive: signingCertSha256 differs/],
      [release({ drive: { ...entry('drive'), filename: 'drive.apk' } }), /apps\.drive: filename/],
      [release({ drive: { ...entry('drive'), versionCode: 0 } }), /apps\.drive: versionCode/],
      [release({ drive: { ...entry('drive'), sha256: 'ABC' } }), /apps\.drive: sha256/],
      [release({ drive: { ...entry('drive'), bytes: 0 } }), /apps\.drive: bytes/],
    ]
    for (const [content, error] of bad) {
      await withRelease(content, (dir) => expect(() => loadAndroidRelease(dir), String(error)).toThrow(error))
    }
    await withRelease('{ nope', (dir) => expect(buildSupportSite({ chrome, storeDir: dir })).rejects.toThrow(/android-release\.json: not JSON/))
    await withRelease(undefined, (dir) => expect(loadAndroidRelease(dir)).toBeNull())
  })
})
