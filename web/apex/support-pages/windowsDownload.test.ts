// @vitest-environment node
//
// The Windows download pages (windowsDownload.ts; desktop-windows-port.md §5.1 D6). Pins: rendered from
// the committed store/windows-release.json at build time; "not available yet" (no package link, no
// certificate, no command) without it; a malformed file fails the build; the app pages' Windows button
// links only a released app; and the guide says what the decision requires (Control first, trust the
// certificate once with its thumbprint printed, TrustedPeople and never Root, how to check and undo).
//
// ⚠ Every build here uses its own temporary store directory, so these tests do not change meaning
// with each release the publish step commits.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { APEX_DIR, buildSupportSite } from './generate.ts'
import { loadSupportChrome } from './loadChrome.ts'
import { WINDOWS_APPS, WINDOWS_DOWNLOAD, WINDOWS_RELEASE_FILE, loadWindowsRelease } from './windowsDownload.ts'

const chrome = await loadSupportChrome('test')

const HEX = (c: string) => c.repeat(64)
const THUMB = 'A234D3C4565D7FEB67AB52783DE63AE660075929'
const BASE = 'https://releases.tenshu.app/sha256/'
const NAME = (app: string) => `Tenshu${app[0]!.toUpperCase()}${app.slice(1)}`
// The shape scripts/lib/windows_publish.py writes (docs/how-to/windows-release.md §3, schema 1).
const release = (apps: Record<string, unknown>, extra: Record<string, unknown> = {}) => ({
  about: 'Generated by scripts/windows-direct-publish.sh — do not edit.',
  schema: 1,
  base: BASE,
  version: '1.0.1',
  packageVersion: '1.0.1.0',
  arch: 'x64',
  minimumWindows: '10.0.17763.0',
  publisher: 'CN=Tenshu Beta',
  publisherId: 'xs68hk207yka0',
  certificate: { file: 'TenshuBeta.cer', url: `${BASE}${HEX('c')}.cer`, sha256: HEX('c'), bytes: 812, thumbprint: THUMB, notAfter: '2029-11-16' },
  commit: '0123456789abcdef0123456789abcdef01234567',
  published: '2026-11-17',
  apps,
  ...extra,
})
const entry = (app: string, c = 'a', bytes = 311_000_000) => ({
  // Partner Center's reserved Package/Identity/Name (desktop-windows-port.md D7).
  identityName: `62647B3nedikt.${NAME(app)}`,
  file: `${NAME(app)}-1.0.1.msix`,
  url: `${BASE}${HEX(c)}.msix`,
  sha256: HEX(c),
  bytes,
})

async function withRelease<T>(content: unknown | undefined, run: (dir: string) => Promise<T> | T): Promise<T> {
  const dir = mkdtempSync(join(tmpdir(), 'windows-release-'))
  try {
    if (content !== undefined) writeFileSync(join(dir, WINDOWS_RELEASE_FILE), typeof content === 'string' ? content : JSON.stringify(content))
    return await run(dir)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

const fileOf = (files: readonly { file: string; content: string }[], name: string) => {
  const f = files.find((x) => x.file === name)
  if (!f) throw new Error(`no ${name}`)
  return f.content
}
const article = (html: string) => html.slice(html.indexOf('<article'), html.indexOf('</article>'))
const windowsButton = (html: string) => /<li data-os="windows"[^>]*>(.*?)<\/li>/.exec(html)?.[0] ?? ''

describe('Windows download pages', () => {
  it('without a release file: every app and language is built, says "not available yet", and hands out no package, certificate or command', async () => {
    const site = await withRelease(undefined, (dir) => buildSupportSite({ chrome, storeDir: dir }))
    for (const app of WINDOWS_APPS) {
      for (const lang of ['en', 'de', 'fr']) {
        const html = fileOf(site.files, `apps/${app}/download/windows/${lang}/index.html`)
        const body = article(html)
        expect(html, `${app} ${lang}`).toContain(`<link rel="canonical" href="https://tenshu.app/apps/${app}/download/windows/${lang}">`)
        expect(html).toContain(`<link rel="alternate" hreflang="x-default" href="https://tenshu.app/apps/${app}/download/windows">`)
        expect(body, `${app} ${lang}`).toContain(`data-msix-unavailable="${app}"`)
        expect(body).toContain(WINDOWS_DOWNLOAD[lang]!.notYet)
        expect(body).not.toMatch(/\.msix"|\.cer"|data-msix="/)
        expect(body).not.toContain('Import-Certificate')
        expect(body).toContain('data-certificate-unavailable')
      }
    }
  })

  it('without a release file: every app page shows Windows as coming soon, never a link', async () => {
    const site = await withRelease(undefined, (dir) => buildSupportSite({ chrome, storeDir: dir }))
    for (const app of ['control', 'drive', 'photos']) {
      const button = windowsButton(fileOf(site.files, `apps/${app}/en/index.html`))
      expect(button, app).toContain('data-soon')
      expect(button).not.toContain('href=')
    }
  })

  it('with a release: the published apps link their package, show size, version, checksum, the certificate and its thumbprint', async () => {
    const site = await withRelease(release({ control: entry('control', 'a'), drive: entry('drive', 'b', 121_000_000) }), (dir) =>
      buildSupportSite({ chrome, storeDir: dir }),
    )
    const control = article(fileOf(site.files, 'apps/control/download/windows/en/index.html'))
    expect(control).toContain(`href="${BASE}${HEX('a')}.msix"`)
    expect(control).toContain('Version 1.0.1 · 311 MB · Windows 10 version 1809 or later, 64-bit (x64)')
    expect(control).toContain(`<code class="break-all">${HEX('a')}</code>`)
    expect(control).toContain(`href="${BASE}${HEX('c')}.cer"`)
    expect(control).toContain(`data-thumbprint="${THUMB}"`)
    // ⚠⚠ The command checks the published thumbprint BEFORE it imports (T-WD-01), then trusts it in TrustedPeople on
    // the local machine, never Root: a root would vouch for websites too.
    const command = /<pre[^>]*data-trust-command><code>(.*?)<\/code><\/pre>/.exec(control)?.[1] ?? ''
    expect(command).toContain('$f = &quot;$env:USERPROFILE\\Downloads\\TenshuBeta.cer&quot;')
    expect(command.indexOf(`.Thumbprint -eq '${THUMB}'`)).toBeGreaterThan(-1)
    expect(command.indexOf(`.Thumbprint -eq '${THUMB}'`)).toBeLessThan(command.indexOf('Import-Certificate'))
    expect(command).toContain('Import-Certificate -FilePath $f -CertStoreLocation Cert:\\LocalMachine\\TrustedPeople')
    expect(command).toContain('NOT the Tenshu certificate')
    expect(control).not.toMatch(/Cert:\\\\?LocalMachine\\\\?Root|Cert:\\CurrentUser\\Root/)
    // The undo names the certificate as Windows lists it.
    expect(control).toContain('delete &quot;Tenshu Beta&quot;')
    const drive = article(fileOf(site.files, 'apps/drive/download/windows/en/index.html'))
    expect(drive).toContain('href="/apps/control/download/windows/en">Tenshu Control</a> first')
    expect(drive).toContain('121 MB')
    // An app the release does not carry stays unavailable, and so does its app-page button.
    const photos = article(fileOf(site.files, 'apps/photos/download/windows/en/index.html'))
    expect(photos).toContain('data-msix-unavailable="photos"')
    expect(windowsButton(fileOf(site.files, 'apps/photos/en/index.html'))).toContain('data-soon')
    expect(windowsButton(fileOf(site.files, 'apps/control/en/index.html'))).toContain('href="/apps/control/download/windows"')
    expect(windowsButton(fileOf(site.files, 'apps/drive/en/index.html'))).toContain('href="/apps/drive/download/windows"')
  })

  it('keeps every section and the em-dash rule in each language; the translations are unreviewed', async () => {
    const site = await withRelease(release({ control: entry('control') }), (dir) => buildSupportSite({ chrome, storeDir: dir }))
    const ids = (html: string) => [...html.matchAll(/<h2 id="([^"]+)"/g)].map((m) => m[1])
    const en = ids(article(fileOf(site.files, 'apps/control/download/windows/en/index.html')))
    expect(en).toEqual(['certificate', 'install', 'update', 'microsoft-store', 'verify', 'uninstall', 'requirements', 'all-apps'])
    for (const lang of ['de', 'fr']) {
      const body = article(fileOf(site.files, `apps/control/download/windows/${lang}/index.html`))
      expect(ids(body), lang).toEqual(en)
      expect(body, lang).toContain(`data-thumbprint="${THUMB}"`)
    }
    for (const lang of ['en', 'de', 'fr']) {
      const body = article(fileOf(site.files, `apps/drive/download/windows/${lang}/index.html`))
      expect(body, lang).not.toContain('—')
    }
    expect(Object.fromEntries(Object.entries(WINDOWS_DOWNLOAD).map(([l, p]) => [l, p.reviewed]))).toEqual({ en: true, de: false, fr: false })
  })

  it('lists the catalogue apps in catalogue order (scripts/lib/app-catalogue.sh TENSHU_APP_KEYS)', () => {
    const sh = readFileSync(join(APEX_DIR, '..', '..', 'scripts', 'lib', 'app-catalogue.sh'), 'utf8')
    const keys = /^TENSHU_APP_KEYS="([^"]*)"/m.exec(sh)
    expect(keys, 'TENSHU_APP_KEYS in app-catalogue.sh').not.toBeNull()
    expect([...WINDOWS_APPS]).toEqual(keys![1]!.split(' '))
  })

  it('a malformed release fails the build rather than publishing a wrong link or thumbprint', async () => {
    const cert = release({}).certificate
    const bad: [unknown, RegExp][] = [
      ['{ nope', /not JSON/],
      [release({}, { schema: 2 }), /schema must be 1/],
      [release({}, { base: 'https://releases.tenshu.app/' }), /base must be/],
      [release({}, { arch: 'arm64' }), /arch must be x64/],
      [release({}, { version: '1.0' }), /version must be x\.y\.z/],
      [release({}, { minimumWindows: '17763' }), /minimumWindows/],
      [release({}, { publisher: 'CN=Tenshu Local Test' }), /publisher must be a release/],
      [release({}, { certificate: { ...cert, thumbprint: 'abc' } }), /thumbprint/],
      [release({}, { certificate: { ...cert, url: `${BASE}${HEX('d')}.cer` } }), /certificate\.url/],
      [release({ chess: entry('chess') }), /unknown app "chess"/],
      [release({ photos: entry('photos') }), /apps\.photos: has no Windows package identity/],
      [release({ drive: { ...entry('drive'), identityName: 'Tenshu.Drive2' } }), /apps\.drive: identityName/],
      [release({ drive: { ...entry('drive'), url: `${BASE}${HEX('b')}.msix` } }), /apps\.drive: url must be base/],
      [release({ drive: { ...entry('drive'), file: 'TenshuDrive-1.0.0.msix' } }), /apps\.drive: file/],
      [release({ drive: { ...entry('drive'), bytes: 0 } }), /apps\.drive: bytes/],
    ]
    for (const [content, error] of bad) {
      await withRelease(content, (dir) => expect(() => loadWindowsRelease(dir), String(error)).toThrow(error))
    }
    await withRelease('{ nope', (dir) => expect(buildSupportSite({ chrome, storeDir: dir })).rejects.toThrow(/windows-release\.json: not JSON/))
  })
})
