import java.util.Base64
import java.util.Properties

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.android.kotlin.multiplatform.library)
}

// ---- The build-configured issuer (entitlement-trust-anchor-distribution.md D3a) ----------------
//
// `tenshu.extraIssuer` / `TENSHU_EXTRA_ISSUER` = `<publisherId>:<base64 Ed25519 public key>` adds ONE
// issuer to the client's compiled-in trust set, for a build that talks to a non-production plane
// whose commerce signs with its own seed (the dev lab: `tenshu.commerce.dev`). Same precedence as the
// relay / commerce origins in `:control-shared-proxy`: `-P` → env → `local.properties` → none
// (with `gradle.properties` ranked beside `local.properties`, for the reason below).
//
// ⚠⚠ It ADDS, and only under a NEW id. The built-in ids are refused here and `publicKeysFor`
// resolves them first, so no value of this variable can replace or widen production's anchor.
// ⚠ A build WITHOUT it is indistinguishable until a record fails as "unknown publisher" — which is
// why the proxy prints its trusted publisher ids at startup (`initEntitlementStorage`).
fun identityLocalProperty(key: String): String? {
    val file = rootProject.file("local.properties")
    if (!file.exists()) return null
    val props = Properties().apply { file.inputStream().use { load(it) } }
    return props.getProperty(key)?.takeIf { it.isNotBlank() }
}

// ⚠⚠ WHERE it came from is compiled in too. `local.properties` and `gradle.properties` (the
// project's and `~/.gradle`'s) are STANDING files: a line left there after an Android dev-lab build
// would otherwise reach every later build from this machine, including a production web image —
// which has no release variant to refuse it. So the web trusts the issuer only when THIS invocation
// was handed it; see `issuerInForce`.
// ⚠ `findProperty` cannot tell the two apart — it answers from `gradle.properties` as readily as
// from `-P` — so the explicit read goes to the invocation's own start parameters.
val explicitExtraIssuerSpec: String? =
    gradle.startParameter.projectProperties["tenshu.extraIssuer"]?.takeIf { it.isNotBlank() }
        ?: System.getenv("TENSHU_EXTRA_ISSUER")?.takeIf { it.isNotBlank() }
val standingExtraIssuerSpec: String? =
    (findProperty("tenshu.extraIssuer") as String?)?.takeIf { it.isNotBlank() }
        ?: identityLocalProperty("tenshu.extraIssuer")
val extraIssuerSpec: String = explicitExtraIssuerSpec ?: standingExtraIssuerSpec ?: ""
val extraIssuerFromStandingFile: Boolean = explicitExtraIssuerSpec == null && extraIssuerSpec.isNotEmpty()

val extraIssuerId: String = extraIssuerSpec.substringBefore(':', "")
val extraIssuerKey: ByteArray =
    if (extraIssuerSpec.isEmpty()) {
        ByteArray(0)
    } else {
        val builtIn = setOf("tenshu.dev", "tenshu.commerce")
        if (!Regex("^[a-z0-9][a-z0-9.-]*$").matches(extraIssuerId)) {
            throw GradleException(
                "tenshu.extraIssuer must be '<publisherId>:<base64 key>', e.g. " +
                    "tenshu.commerce.dev:AAAA…=  (got a publisher id of '$extraIssuerId')"
            )
        }
        if (extraIssuerId in builtIn) {
            throw GradleException(
                "tenshu.extraIssuer may not name the built-in issuer '$extraIssuerId': it adds a NEW " +
                    "issuer, it never changes the keys an existing one is trusted under."
            )
        }
        val decoded = runCatching {
            Base64.getDecoder().decode(extraIssuerSpec.substringAfter(':'))
        }.getOrNull()
        if (decoded == null || decoded.size != 32) {
            throw GradleException(
                "tenshu.extraIssuer's key must be base64 of a 32-byte Ed25519 public key " +
                    "(got ${decoded?.size ?: "undecodable"} bytes)."
            )
        }
        decoded
    }

val buildConfiguredIssuerDir = layout.buildDirectory.dir("generated/buildConfiguredIssuer")
val generateBuildConfiguredIssuer = tasks.register("generateBuildConfiguredIssuer") {
    val outDir = buildConfiguredIssuerDir
    val id = extraIssuerId
    val keyLiteral = extraIssuerKey.joinToString(", ")
    inputs.property("publisherId", id)
    inputs.property("publicKey", keyLiteral)
    val fromStandingFile = extraIssuerFromStandingFile
    inputs.property("fromStandingFile", fromStandingFile)
    outputs.dir(outDir)
    doLast {
        val pkgDir = outDir.get().dir("org/tenshu/identity").asFile
        pkgDir.mkdirs()
        pkgDir.resolve("BuildConfiguredIssuer.kt").writeText(
            """
            package org.tenshu.identity

            /**
             * The one issuer this BUILD was told to trust on top of the built-in set. GENERATED by
             * `generateBuildConfiguredIssuer` from `tenshu.extraIssuer` / `TENSHU_EXTRA_ISSUER` — do
             * not edit by hand. An empty id means none was configured, which is every production
             * build. Read only through [EntitlementSignature].
             */
            internal object BuildConfiguredIssuer {
                const val PUBLISHER_ID: String = "$id"
                val PUBLIC_KEY: ByteArray = byteArrayOf($keyLiteral)

                /**
                 * True when the value came from a standing file (`local.properties`, any
                 * `gradle.properties`) rather than this invocation's `-P` / environment.
                 */
                const val FROM_STANDING_FILE: Boolean = $fromStandingFile
            }

            """.trimIndent() + "\n"
        )
    }
}

