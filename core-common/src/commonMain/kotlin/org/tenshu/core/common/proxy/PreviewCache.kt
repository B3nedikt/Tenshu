package org.tenshu.core.common.proxy

/**
 * Persistent, content-keyed cache for generated image previews.
 *
 * **Motivation (`docs/tech-debt.md` §"File Previews Are Regenerated From the
 * Full File on Every Access (No Cache)").** `File.Relation.Preview` is a
 * `dynamicPropertyRelation`, so each `GetPreview` call ran the full
 * generate path (`GetData` → full-res decode → scale → re-encode) and
 * persisted nothing. On Android this blocks the Binder transaction long
 * enough to trip the system watchdog (~20× full-JPEG decode/rescale on a
 * 20-photo folder kills both processes). This cache is the Phase 1 cure:
 * cache-hit → cheap byte read; cache-miss → run the existing generate
 * path and persist the result so warm reads are free.
 *
 * ### Key shape
 *
 * Entries are keyed by `(contentHash, width, height)` where `contentHash`
 * is the SHA-256 of the source file bytes (hex-encoded, lower-case, 64
 * chars). Content-derived — **not** path-derived — so:
 *
 *  - The same source byte-stream stored at two paths shares one cache
 *    entry (cheap; same preview anyway).
 *  - Overwriting a file at the same path with new content yields a new
 *    content hash, so a new cache key; the old entry orphans until GC
 *    (Phase 2).
 *  - The cache never re-binds wrong on overwrite.
 *
 * Width/height discriminate so the same source can be cached at multiple
 * preview sizes without collision.
 *
 * The chosen primitive is SHA-256, distinct from the md5 used by
 * `InMemoryByteArrayDto.uniqueId` — see `tech-debt.md` lines 893+ for the
 * deferred migration of that id; the cache deliberately picks the right
 * primitive for new code so it doesn't ride the deprecated one.
 *
 * ### Size cap
 *
 * `put` returns `false` (no store) if `bytes.size > maxEntryBytes`. A
 * 100×100 PNG/WebP preview is well under the default cap (256 KiB); the
 * cap defends against a misbehaving impl that returned an oversized
 * payload.
 *
 * ### GC
 *
 * Phase 1 ships **no GC**. Orphaned entries (after `replaceFile` /
 * `deleteFile`) linger. Each preview is small (KB, not MB) so growth is
 * bounded by realm churn × preview-size cap; the follow-up
 * proposal/Phase 2 will add a sweep keyed by the live `File` set's
 * content hashes. Same shape as the P3a → P3b split in
 * `docs/adr/0017-file-content-two-plane-channel.md`.
 *
 * ### House Rule #1 (zero-trust relay)
 *
 * Cache lives entirely on Control's local disk — exactly where the
 * source bytes (`FileDatabase`) already live. The relay sees nothing.
 * Threat-model T-C-06 (plaintext in caches / thumbnails) is the
 * existing class this falls under; no new amendment required.
 */
interface PreviewCache {

    /**
     * Maximum size in bytes a single cache entry may hold. `put` of a
     * larger payload is silently skipped (the caller still serves the
     * generated bytes for the current call; only persistence is
     * suppressed). 256 KiB by default.
     */
    val maxEntryBytes: Int
        get() = DEFAULT_MAX_ENTRY_BYTES

    /**
     * Cache lookup. Returns the stored preview bytes if an entry exists
     * for `(contentHash, width, height)`, or `null` on miss.
     */
    fun get(contentHash: String, width: Int, height: Int): ByteArray?

    /**
     * Cache write. Stores `bytes` under `(contentHash, width, height)`.
     * Returns `true` if the entry was persisted, `false` if rejected by
     * the size cap or a backing-store IO failure. The caller MUST treat
     * `false` as a no-op (still serve the generated bytes for this
     * call) — `put` is best-effort persistence, never load-bearing.
     */
    fun put(contentHash: String, width: Int, height: Int, bytes: ByteArray): Boolean

    companion object {
        /** 256 KiB — comfortably above any reasonable 100×100/200×200 preview. */
        const val DEFAULT_MAX_ENTRY_BYTES: Int = 256 * 1024
    }
}

/**
 * No-op cache: every `get` misses, every `put` is dropped on the floor.
 * Used by test fixtures that haven't opted into the cache and as a safe
 * fallback so callers never need a `null`-check around `previewCache`.
 */
object NoOpPreviewCache : PreviewCache {
    override fun get(contentHash: String, width: Int, height: Int): ByteArray? = null
    override fun put(contentHash: String, width: Int, height: Int, bytes: ByteArray): Boolean = false
}
