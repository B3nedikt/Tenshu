/** What reversed the money on a [CreditNote]. Both reverse revenue; only the cause differs. */
enum class CreditNoteKind {
    /** A refund we issued (by hand in the Stripe dashboard — policy §5.4 item 2). */
    Refund,

    /** A dispute the customer won. We never chose it; the money left anyway. */
    Chargeback,
}

/**
 * A **credit note** — money out, reversing all or part of an [Invoice] (WC-1, §4.7).
 *
 * ⚠⚠ This exists because **VAT already remitted on a sale that is later refunded must be corrected
 * in a subsequent OSS return**. A ledger that records only money *in* does not merely omit refunds:
 * it systematically over-states VAT owed, and we over-remit. That is true whether or not the product
 * offers refunds as a courtesy — chargebacks arrive regardless.
 *
 * ⚠ Per §5.2 / D10 a refund is **never an update to the invoice row**: the statutory tables are
 * append-only and a trigger (`CommerceDatabase.APPEND_ONLY_TABLES`) refuses `UPDATE`/`DELETE` on
 * them, so an update would (correctly) fail at runtime. A credit note is its own row with its own sequential number.
 *
 * [amountMinor] is the **positive magnitude** credited, mirroring [Invoice.amountMinor]; the export
 * (WC-4) applies the sign. Keeping both tables positive means a reader cannot mistake which
 * direction a raw row points based on sign alone.
 */
data class CreditNote(
    /** Sequential, store-assigned, from a sequence **separate** from the invoice one (Q4). */
    val number: Long,
    val accountId: String,
    val kind: CreditNoteKind,
    /**
     * The Stripe **refund id** (not the charge id) or **dispute id** this note records. Unique —
     * (a dispute is resolved to its invoice through `Invoice.paymentRef`, WC-6)
     * and that uniqueness is the idempotency key, deliberately at a finer grain than the webhook's
     * event id.
     *
     * ⚠⚠ Keying on the charge would double-count: Stripe's `charge.refunded` carries the
     * **cumulative** `amount_refunded`, and a *second partial refund* on the same charge arrives as
     * a fresh event id with a larger cumulative total. Per-refund ids make both re-delivery and
     * successive partial refunds fall out correctly with no arithmetic.
     */
    val stripeReferenceId: String,
    /**
     * The [Invoice.number] this reverses, when the event let us find it. **Null = unlinked**, and
     * an unlinked note is exactly the one whose VAT could not be apportioned — see
     * [vatAmountMinor]. Disputes are usually unlinked (a dispute names a charge, and we key
     * invoices by session/invoice id).
     */
    val referencesInvoiceNumber: Long?,
    val amountMinor: Long,
    val currency: String,
    /**
     * VAT being credited back, apportioned at the original invoice's rate — or **null when it could
     * not be determined** (an unlinked note).
     *
     * ⚠⚠ Null rather than `0`, deliberately. Zero is a *claim* that no VAT was involved, and a
     * false one would silently corrupt the very per-country total the OSS return is filled from.
     * Null says "this needs a human", and WC-4 must surface it rather than summing past it.
     */
    val vatAmountMinor: Long?,
    val vatRateBasisPoints: Int?,
    /**
     * Copied from the referenced invoice: a VAT correction has to know **which member state's**
     * return to correct, and the credit event itself does not carry a country.
     */
    val billingCountry: String?,
    val issuedAt: Long,
)

/** A [CreditNote] before the store assigns its sequential [CreditNote.number]. */
