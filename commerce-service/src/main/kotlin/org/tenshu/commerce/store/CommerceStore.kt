package org.tenshu.commerce.store

import org.tenshu.commerce.ProductCatalog

/**
 * The mint-authority selection rule (see [CommerceStore.currentEntitlement]): among currently-valid
 * entitlement rows, the one granting the **highest quota** wins, tie-broken by the latest
 * `validUntil`. Extracted so both store backends select identically (the in-memory store is the
 * tested source of truth; the Postgres store must agree byte-for-byte).
 */
internal fun pickCurrentEntitlement(validCandidates: List<EntitlementHistory>): EntitlementHistory? =
    validCandidates.maxWithOrNull(
        compareBy<EntitlementHistory> { ProductCatalog.quotaBytes(it.productId, fallback = 0) }
            .thenBy { it.validUntil },
    )

/**
 * The commerce plane's durable account store (`commerce-accounts-and-sessions.md` §4) — the
 * issuer's first persistence. Mirrors the relay's SPI split (`MailboxStore` / `SyncMailbox` /
 * `SqliteSyncMailbox`): one interface, an in-memory default ([InMemoryCommerceStore], the tested
 * source of truth) and a durable Postgres impl ([PostgresCommerceStore]) selected at startup by
 * `DATABASE_URL`.
 *
 * **A28 lives only here** (House Rule #1): email is never returned in a mint response, never sent
 * to the relay, never written to a realm. OTP codes and session tokens are stored **hashed** — the
 * routing layer hashes before it reaches the store, so a store dump never yields a usable secret.
 *
 * Timestamps are epoch-millis `Long` throughout (consistent with the relay + `EntitlementMinter`).
 */
interface CommerceStore {

    // --- Accounts -----------------------------------------------------------------------------

    /** Insert a new account (id generated by the store). Caller guarantees the email is unbound. */
    fun createAccount(
        emailNormalised: String,
        rail: Rail,
        createdAt: Long,
        displayName: String? = null,
    ): Account

    fun findAccountByEmail(emailNormalised: String): Account?

    fun findAccountById(id: String): Account?

    /**
     * The account carrying [stripeCustomerId], or null. Needed to attribute a **refund or
     * chargeback** (WC-1): those events name a customer, never an email, and inventing an account
     * would be the worst possible guess — an unattributable credit is logged and skipped.
     */
    fun findAccountByStripeCustomerId(stripeCustomerId: String): Account?

    /**
     * Stamp the account verified. ⚠⚠ False = the account is gone; see [attachStripeCustomer].
     *
     * ⚠ Keeps the **first** verification time: every sign-in calls this, and [countVerifiedOpenAccounts]
     * (the signup cap) must count new accounts, not returning ones.
     */
    fun markEmailVerified(accountId: String, verifiedAt: Long): Boolean

    /**
     * Attach a Stripe customer id to an account and mark its rail [Rail.Stripe] — the Stripe rail then
     * owns the payment side (§6). Idempotent; a no-op if the account is gone.
     *
     * ⚠⚠ Returns false when the account row is gone — `expireUnverifiedAccounts` may have deleted it
     * between the caller's lookup and this write. The caller must stop before writing
     * anything else keyed by the id: there are no foreign keys, so later writes would orphan.
     */
    fun attachStripeCustomer(accountId: String, stripeCustomerId: String): Boolean

    /**
     * Mark [accountId] closed at [closedAt] — the **only** thing that makes an account's content
     * eligible for relay reclamation (`retention-quota-model.md` Face A / D4).
     *
     * ⚠⚠ Downstream this leads, after a grace window, to the **permanent deletion** of that
     * owner's content on the relay. It is deliberately explicit and deliberately *not* derived
     * from anything else: an entitlement lapsing, a card failing or a token expiring are all
     * frequent and benign, and none of them means "this person is done". Only a closure does.
     *
     * Idempotent — re-closing keeps the **original** [closedAt], so a repeated call cannot restart
     * the grace clock and quietly extend retention past what the published terms promise.
     * A no-op if the account is gone.
     */
    fun closeAccount(accountId: String, closedAt: Long)

    /**
     * Reopen [accountId]: back to [AccountStatus.Active], and the closure stamp is cleared.
     *
     * ⚠⚠ **This is the whole reason closure records are short-lived.** The relay is told nothing
     * here — reopening works because the sweep stops finding the account, stops re-issuing, and the
     * last record expires on its own. A durable "this owner is closed" fact on the relay would need
     * an *un*-say message, and a missed one would delete a live account's files.
     *
     * ⚠ Clearing [Account.closedAt] means a later re-closure starts a **fresh** grace window, which
     * is correct: the person had their account back in between.
     * Idempotent; a no-op if the account is gone, already active, or **erased** ([eraseAccount]
     * is terminal).
     */
    fun reopenAccount(accountId: String)

    /**
     * **Erase** [accountId]: the self-service account deletion (`commerce-accounts-and-sessions.md`
     * §9.7, Play's account-deletion requirement). In one step it
     *
     * 1. closes the account exactly as [closeAccount] does — keeping an earlier closure's stamp, so
     *    the relay's grace window is never restarted — which is what puts its content on the
     *    existing reclamation path (`retention-quota-model.md` Face A);
     * 2. replaces the email with [ErasedAccounts.tombstoneFor] and clears `email_verified_at` and
     *    `display_name`;
     * 3. deletes every session, every pending OTP for the address (sign-in **and** deletion) and the
     *    marketing-consent row.
     *
     * ⚠⚠ **The row itself stays, pseudonymous, and it has to.** Three things still hang off it:
     * the closure sweep re-mints a short-lived record from `(id, closed_at, live owner)` for as long
     * as the relay's grace window needs (deleting the row would *cancel* the content deletion — the
     * reopen semantics of [reopenAccount]); the cancellation sweep retries from
     * `stripe_customer_id` / `iap_original_txn_id`; and the statutory `invoice` / `credit_note` /
     * `acceptance` rows (§5.2, ~10 years, append-only) reference `account_id`. What is left names no
     * person: an opaque id, timestamps, the rail, the processor's customer reference.
     *
     * ⚠ Erasure is terminal on this plane: the tombstone has no `@`, so no `normaliseEmail` result
     * can ever match it, and the same address registering again gets a **new** account.
     *
     * Idempotent: returns `true` when this call erased the account, `false` when it was already
     * erased or does not exist — a repeated or concurrent call changes nothing.
     */
    fun eraseAccount(accountId: String, erasedAt: Long): Boolean

    /**
     * Every closed account that has a live `ownerId`, for the closure-record sweep.
     *
     * ⚠ An account with no live owner binding is skipped: there is no keyspace to reclaim, and
     * inventing one would be the worst possible guess. ⚠ Ordering is unspecified; callers treat
     * this as a set.
     *
     * ⚠⚠ **An owner that is still live-bound to an account that is NOT closed is skipped too.**
     * The keyspace is the *realm*, not the account, and one realm can be bound to several accounts
     * at once (see [accountIdsForOwner]) — most importantly after an erasure, when the same person
     * signs in again from the same device: the address no longer finds the erased row, so a new
     * account is created and bound to the very `ownerId` the erased one still names. Minting for it
     * would tell the relay to delete the files the new, live account is using. A realm somebody
     * still holds an open account for is not reclaimable, whoever else let go of it.
     */
    fun closedAccountsWithOwners(): List<ClosedAccount>

    /**
     * Delete accounts that are nothing but a code request: never verified, created before
     * [olderThanMs] **and** last requested (`Registration` acceptance) before it, open, never erased,
     * on the Free rail, with no Stripe/IAP reference and no row in any other account table (session,
     * entitlement, owner, invoice, credit note, marketing consent, a non-Registration acceptance).
     * Removes the account, its `Registration` acceptance rows and its email-keyed verification rows
     * (code, deletion code, failed-code log). Returns the number of accounts deleted.
     *
     * ⚠⚠ The only path that deletes `acceptance` rows; Postgres enforces the narrow case (the
     * expiry triggers in [CommerceDatabase]). Policy: privacy notice "unverified accounts".
     */
    fun expireUnverifiedAccounts(olderThanMs: Long): Int

    /**
     * Open (not closed, not erased) accounts whose email was verified at or after [verifiedSinceMs]
     * — what the signup cap counts. `0` counts every verified open account. Unverified accounts are
     * left out on purpose: they hold no storage, and counting them would let anyone fill the cap
     * with code requests for addresses they do not own.
     */
    fun countVerifiedOpenAccounts(verifiedSinceMs: Long): Int

    /**
     * Closed accounts that carry a Stripe customer or a store subscription reference
     * ([Account.iapOriginalTxnId]) and were closed at or after [closedSince] — the retry set for
     * subscription cancellation.
     *
     * ⚠ Deliberately **not** [closedAccountsWithOwners]: that one INNER JOINs the live owner
     * because reclamation needs a keyspace, but billing does not care about owners at all. An
     * account with no bound owner can still have a live subscription, and missing it is exactly
     * the "closed but still charged" case this exists to prevent.
     *
     * ⚠ [closedSince] bounds the sweep so it does not grow without limit as closed accounts
     * accumulate. Cancellation is idempotent and normally succeeds on the first attempt at close
     * time; this window is the self-healing tail, not the primary path.
     */
    fun closedAccountsWithBilling(closedSince: Long): List<Account>


    // --- Owner binding (the A30 link; re-bindable, §3.4) ---------------------------------------

    /**
     * Bind [ownerId] as the account's **live** owner. Supersedes any existing live binding
     * (`superseded_at := boundAt`) and inserts a fresh live row — at most one row with
     * `superseded_at IS NULL` per account. This is what makes purchase recovery after
     * recovery-code loss work (the old `ownerId` is dead; the new one inherits the entitlement).
     */
    fun bindOwner(accountId: String, ownerId: String, boundAt: Long)

    /** The account's current live `ownerId`, or null if none is bound. */
    fun liveOwner(accountId: String): String?

    /** The account currently bound (live) to [ownerId], or null. */
    fun accountIdForOwner(ownerId: String): String?

    /**
     * **Every** account live-bound to [ownerId].
     *
     * ⚠⚠ More than one is normal, and [accountIdForOwner] hides it: a binding is superseded per
     * *account*, never per owner, so a realm that signs in with a second email is bound to both
     * accounts at once. Anything that asks "what does this realm already pay for" has to ask all
     * of them — the one-subscription guard looked at the signed-in account alone, and a realm
     * bought the same plan three times under three emails.
     */
    fun accountIdsForOwner(ownerId: String): List<String>

    // --- Email verification (OTP, short-lived) -------------------------------------------------

    fun putEmailVerification(emailNormalised: String, codeHash: String, expiresAt: Long)

    fun getEmailVerification(emailNormalised: String): EmailVerification?

    fun incrementVerificationAttempts(emailNormalised: String)

    fun deleteEmailVerification(emailNormalised: String)

    // --- Commerce sessions (opaque token, hashed) ----------------------------------------------

    fun createSession(tokenHash: String, accountId: String, createdAt: Long, expiresAt: Long)

    fun getSession(tokenHash: String): Session?

    fun deleteSession(tokenHash: String)

    /**
     * Delete every session of [accountId]; returns how many. Used when a review account's code is
     * rotated or withdrawn (T-CB-12), so a session minted under the old code does not outlive it.
     */
    fun deleteSessionsForAccount(accountId: String): Int

    /**
     * How many of [accountId]'s sessions are still valid at [nowMs] — the operator's "is anyone
     * signed in on a device right now" signal, the other half of CE-5's deferred console work.
     *
     * ⚠ A **count**, never the sessions themselves: a session token is a live credential, and the
     * console has no reason to display one. Counting answers the operator's question without
     * putting a usable secret on the highest-risk page in the system.
     */
    fun countActiveSessions(accountId: String, nowMs: Long): Int

    // --- Entitlement ledger --------------------------------------------------------------------

    fun appendEntitlementHistory(entry: EntitlementHistory)

    /**
     * The account's currently-valid entitlement (`nowMs` within `[validFrom, validUntil]`), or null.
     * When several overlap, the one granting the **highest quota** wins (tie-broken by the latest
     * `validUntil`). This is the mint authority: `/mint` + `/token` only issue when this is non-null
     * (§4.3).
     *
     * Highest-quota (not merely latest-`validUntil`) is load-bearing because paid tiers coexist with the
     * ~permanent Free row: a Free-then-upgrade account carries both a 10-year Free row and a
     * ~monthly paid row, and the paid tier must win while it is valid — then gracefully fall back to
     * Free when the paid window lapses (the "stop reissuing" revocation model, §6).
     */
    fun currentEntitlement(accountId: String, nowMs: Long): EntitlementHistory?

    /**
     * End every still-valid **paid** ([EntitlementSource.Stripe]) grant of [accountId] at
     * [revokedAt], so [currentEntitlement] falls back to whatever else the account holds (Free).
     * Returns how many grants were ended; idempotent.
     *
     * ⚠⚠ The one place this ledger is not append-only. "Stop reissuing" is the ordinary revocation
     * (§6) and needs no write, but it only works when the money stops: a lost chargeback takes the
     * payment back while the grant it bought still runs to the end of the period. The credit note
     * written for the chargeback is the record of why the window was cut.
     *
     * ⚠ Redeemed and Free grants are untouched — a chargeback reverses a card payment, not a code.
     */
    fun revokePaidEntitlements(accountId: String, revokedAt: Long): Int =
        endEntitlements(accountId, EntitlementSource.Stripe, revokedAt)

    /**
     * End every still-valid grant of [accountId] that came from [source], at [endedAt]. Returns how
     * many were ended; idempotent. The general form of [revokePaidEntitlements], for a store
     * subscription that was refunded, revoked or replaced by another rail (D6).
     */
    fun endEntitlements(accountId: String, source: EntitlementSource, endedAt: Long): Int

    /**
     * Record that [accountId] now buys through a store [rail], and the store's reference for the
     * subscription ([storeRef]: Google's purchase token, Apple's original transaction id), so a
     * later switch to another rail can stop it.
     */
    fun setStoreRail(accountId: String, rail: Rail, storeRef: String)

    // --- Redemption codes (the whitelist's successor as a founder/privacy seed, §4.3) ----------

    fun putRedemptionCode(code: RedemptionCode)

    fun getRedemptionCode(codeHash: String): RedemptionCode?

    /** Atomically bump `used_count`. Caller has already checked `used_count < max_uses`. */
    fun incrementRedemptionUse(codeHash: String)

    // --- Consent (§5.1) ------------------------------------------------------------------------

    /**
     * Append an acceptance row — only while its account exists (Postgres: `INSERT … SELECT … FROM
     * account … FOR SHARE`, so it waits out a concurrent expiry sweep and then inserts nothing).
     * ⚠⚠ False = the account is gone; see [attachStripeCustomer]. Without this a request racing
     * the sweep would leave an orphan Registration row the expiry trigger can never delete.
     */
    fun recordAcceptance(acceptance: Acceptance): Boolean

    fun setMarketingConsent(consent: MarketingConsent)

    // --- Stripe billing (§6) -------------------------------------------------------------------

    /**
     * Append a statutory [invoice] row, assigning the next sequential invoice **number**
     * (`commerce-accounts-and-sessions.md` §5.2 — append-only, ~10-year retention, survives account
     * erasure; a trigger in `CommerceDatabase` refuses `UPDATE`/`DELETE`). Returns the stored row
     * with its assigned number.
     */
    fun appendInvoice(draft: InvoiceDraft): Invoice

    /**
     * The statutory invoice written for [stripeInvoiceId], or null. Narrow lookup, not a listing:
     * a credit note has to find the invoice it reverses in order to apportion VAT at the **original
     * rate** (WC-1).
     */
    fun findInvoiceByStripeId(stripeInvoiceId: String): Invoice?

    /**
     * The invoice settled by [paymentRef] (a PaymentIntent or charge id), or null — the lookup a
     * **chargeback** needs (WC-6), since a dispute names a payment and never an invoice.
     *
     * ⚠ Returns null for every invoice written before WC-6: the reference was not captured then and
     * cannot be reconstructed, so those disputes stay unreconciled by construction.
     */
    fun findInvoiceByPaymentRef(paymentRef: String): Invoice?

    /**
     * Statutory invoices issued in **`[fromInclusive, toExclusive)`**, ordered by [Invoice.number]
     * ascending (WC-2). The one read path of this table besides `nextval`.
     *
     * ⚠⚠ **Half-open on purpose.** A VAT return is filed per period, and adjacent periods share a
     * boundary instant; closed-on-both-ends ranges would count a midnight row in *two* quarters —
     * once as revenue and once again as a correction basis. Half-open makes consecutive calls tile
     * the timeline exactly, with no row counted twice and none skipped.
     *
     * ⚠ Ordered by number, not by `issuedAt`: the sequence is the statutory ordering, and two rows
     * can legitimately share a millisecond.
     */
    fun listInvoices(fromInclusive: Long, toExclusive: Long): List<Invoice>

    /**
     * Credit notes issued in **`[fromInclusive, toExclusive)`**, ordered by [CreditNote.number]
     * ascending — the money-out side of the same window as [listInvoices], with the same half-open
     * semantics and for the same reason.
     */
    fun listCreditNotes(fromInclusive: Long, toExclusive: Long): List<CreditNote>

    /**
     * Every entitlement row ever written for [accountId], oldest first — the operator view CE-5
     * deferred ("no entitlement history, no session view"). Answers "what has this account actually
     * been granted, and by which rail", which [currentEntitlement] cannot: that one deliberately
     * returns a single winner.
     */
    fun listEntitlementHistory(accountId: String): List<EntitlementHistory>

    /**
     * Append a [CreditNote] (money out — WC-1, §4.7), assigning the next sequential credit-note
     * number from a sequence **separate** from the invoice one.
     *
     * Returns **null when [CreditNoteDraft.stripeReferenceId] is already recorded** — the caller
     * has re-seen a refund/dispute it already credited. ⚠ This is the idempotency boundary that
     * matters: webhook-level event-id dedupe does *not* cover a second partial refund on the same
     * charge, which arrives as a genuinely new event carrying a cumulative total.
     */
    fun appendCreditNote(draft: CreditNoteDraft): CreditNote?

    /** Whether a Stripe webhook event id has already been processed (idempotency, §6). */
    fun stripeEventSeen(eventId: String): Boolean

    /** Record a Stripe webhook event id as processed. Call after the event's writes succeed. */
    fun recordStripeEvent(eventId: String, receivedAt: Long)

    // --- Admin console (§4.5, read-only) -------------------------------------------------------

    /**
     * The read-only admin view: each account joined to its live owner + current
     * entitlement. [query] (case-insensitive) filters by email **or** live `ownerId` substring;
     * null/blank returns all. This is the only A28⨯A30-joining read surface — see [AdminAccountRow].
     */
    fun listAccountsForAdmin(query: String?, nowMs: Long): List<AdminAccountRow>

    // --- Liveness --------------------------------------------------------------------------------

    /**
     * Round-trip the backing store, throwing if it cannot be reached. The **cheapest** query that
     * still proves an end-to-end path: borrow a pooled connection, ask the server, hand it back.
     *
     * ⚠⚠ Exists because *"the process is up"* and *"the process can serve"* are different claims:
     * a static `GET /` proves only that Ktor is listening. After the Postgres container is recreated,
     * Hikari can still report `total=10, idle=10` while `pg_stat_activity` shows **zero** connections
     * from the app — the pool describes sockets that are gone, because it validates on borrow and
     * nothing has borrowed yet. Only an actual round-trip distinguishes the two states.
     *
     * ⚠ Must stay side-effect free and unauthenticated-safe: it is reachable without a session.
     */
    fun probe()
}

/** Which billing system owns the payment side. Does not change that email is the recovery anchor. */
enum class Rail { Free, Stripe, IapApple, IapGoogle, Redeem }

/**
 * Where an entitlement-history row came from.
 *
 * ⚠ The two stores are separate values, not one `Iap` plus the account's [Rail]: an account's rail
 * changes when it buys elsewhere, and a still-running Apple grant must stay *Apple's* — it is the
 * one rail nobody but the user can stop (`commerce-store-link-out.md` D6). Persisted by name; no
 * row ever carried the old `Iap`.
 */
enum class EntitlementSource { Stripe, IapApple, IapGoogle, Redeem, Free }

/**
 * Account lifecycle state. [Closed] is terminal for *content*: after a configurable grace window
 * the relay reclaims that owner's keyspace (`retention-quota-model.md` Face A / D4).
 *
 * ⚠ Suspension is still absent, and deliberately so — a suspension must NOT be reclaimable, and
 * the only way to guarantee that today is for the state not to exist. Add it with its own
 * non-reclaim semantics, never by widening [Closed].
 */
enum class AccountStatus { Active, Closed }

/**
 * The two derived keys erasure has to know about. Kept beside the store because [CommerceStore.eraseAccount]
 * must delete what the routes write under them.
 */
object ErasedAccounts {
    /**
     * The `email_normalised` an erased account carries. Unique per account (the column is `UNIQUE`)
     * and **contains no `@`**, so `normaliseEmail` can never produce it: a sign-in, a webhook or an
     * admin lookup by address cannot land on an erased row.
     */
    fun tombstoneFor(accountId: String): String = "erased:$accountId"

    fun isTombstone(emailNormalised: String): Boolean = emailNormalised.startsWith("erased:")

    /**
     * The `email_verification` key a **deletion** code is stored under — separate from the sign-in
     * code's key (the bare address), so neither kind of code can be spent as the other: a code
     * mailed for signing in must never be able to delete the account, and requesting a deletion
     * code must not silently invalidate a sign-in in flight.
     *
     * ⚠⚠ Disjoint only because `normaliseEmail` rejects `:` — otherwise `/register` with the string
     * `account-deletion:victim@x.com` would write a sign-in code under the victim's deletion key.
     */
    fun deletionOtpKey(emailNormalised: String): String = "account-deletion:$emailNormalised"

    /**
     * Where a deletion request for an address **no account uses** writes its throwaway code, so that
     * branch does the same database work as the real one (timing parity) without storing the
     * stranger's address. Never confirmable: no address normalises to it (no `@`), and confirm looks
     * up only [deletionOtpKey].
     */
    const val DECOY_OTP_KEY: String = "account-deletion-decoy"

    /**
     * The ordinary one-time code's failed-check log for an address (D15, [org.tenshu.commerce.PersistedFailureLimit]).
     * Disjoint for the same reason as [deletionOtpKey]; deleted by erasure because it names the address.
     */
    fun otpFailuresKey(emailNormalised: String): String =
        org.tenshu.commerce.PersistedFailureLimit.OTP_FAILURES_PREFIX + org.tenshu.commerce.sha256Hex(emailNormalised)
}

/** A closed account that still has a live owner binding — the input to a closure-record mint. */
data class ClosedAccount(
    val accountId: String,
    val ownerId: String,
    val closedAt: Long,
)

data class Account(
    val id: String,
    val emailNormalised: String,
    val emailVerifiedAt: Long?,
    val createdAt: Long,
    val status: AccountStatus,
    /** When the account was closed; null while [AccountStatus.Active]. The grace clock's origin. */
    val closedAt: Long? = null,
    /**
     * When the account's personal data was erased ([CommerceStore.eraseAccount]); null otherwise.
     * Non-null implies [status] is [AccountStatus.Closed] and [emailNormalised] is a tombstone.
     */
    val erasedAt: Long? = null,
    val rail: Rail,
    /** Populated by the Stripe rail; null otherwise. */
    val stripeCustomerId: String? = null,
    /** Populated by the IAP rail; null otherwise. */
    val iapOriginalTxnId: String? = null,
    val displayName: String? = null,
)

data class AccountOwner(
    val accountId: String,
    val ownerId: String,
    val boundAt: Long,
    /** Null = the live binding. Non-null = superseded by a later re-bind (§3.4). */
    val supersededAt: Long? = null,
)

data class EntitlementHistory(
    val accountId: String,
    val productId: String,
    val validFrom: Long,
    val validUntil: Long,
    val source: EntitlementSource,
    val issuedAt: Long,
)

data class EmailVerification(
    val emailNormalised: String,
    val codeHash: String,
    val expiresAt: Long,
    val attempts: Int,
)

data class RedemptionCode(
    val codeHash: String,
    val productId: String,
    val maxUses: Int,
    val usedCount: Int,
    /** Null = no expiry. */
    val expiresAt: Long? = null,
) {
    fun isRedeemable(nowMs: Long): Boolean =
        usedCount < maxUses && (expiresAt == null || nowMs <= expiresAt)
}

data class Session(
    val tokenHash: String,
    val accountId: String,
    val createdAt: Long,
    val expiresAt: Long,
) {
    fun isValid(nowMs: Long): Boolean = nowMs <= expiresAt
}

data class Acceptance(
    val accountId: String,
    val tosVersion: String,
    val privacyVersion: String?,
    val acceptedAt: Long,
    val ip: String? = null,
    val kind: AcceptanceKind = AcceptanceKind.Registration,
)

/**
 * What a stored [Acceptance] row is evidence *of*. Both are contract formation, but they are
 * different acts at different moments and an evidence trail that cannot tell them apart is worth
 * much less than one that can.
 */
enum class AcceptanceKind {
    /** The terms accepted when the account was created (`/register`). */
    Registration,

    /**
     * The purchase-time acknowledgement that the service starts **immediately** and that starting
     * it forfeits the EU 14-day right of withdrawal (policy §5.4).
     *
     * ⚠ This is the row that decides whether a withdrawal request inside 14 days is refundable.
     * Without it the statutory right stands, whatever the terms say — which is exactly why
     * `/commerce/checkout` refuses a purchase that does not carry the acknowledgement.
     */
    PurchaseWithdrawalWaiver,
}

data class MarketingConsent(
    val accountId: String,
    val granted: Boolean,
    val changedAt: Long,
)

/**
 * A statutory invoice row (§5 / §5.2). Amounts are minor units (e.g. cents) to avoid float drift;
 * [vatRateBasisPoints] is hundredths of a percent (1900 = 19.00%). [billingCountry] + [ipCountry]
 * are the **two non-contradictory location evidences** an OSS VAT filing needs (§5). Append-only:
 * never edited or deleted once written.
 */
data class Invoice(
    /** Sequential, store-assigned (Q4 — jurisdiction-scoped numbering is a later refinement). */
    val number: Long,
    val accountId: String,
    /** Provenance back to the Stripe invoice, if any. */
    val stripeInvoiceId: String?,
    val amountMinor: Long,
    val currency: String,
    val vatAmountMinor: Long,
    val vatRateBasisPoints: Int,
    val billingCountry: String?,
    val ipCountry: String?,
    val issuedAt: Long,
    /**
     * The Stripe **payment** this invoice was settled by — a PaymentIntent id where there is one,
     * else a charge id (WC-6).
     *
     * ⚠⚠ This is what lets a **chargeback** find its invoice. A dispute names a charge (and usually a
     * PaymentIntent), never an invoice, so without this a lost dispute cannot be apportioned to a
     * country and lands in the export's `(unreconciled)` bucket — leaving a fully-reversed sale
     * reported in full while an equal figure sits unattributed.
     *
     * ⚠ Null on rows written before WC-6 and on any payload that carries no payment reference, so
     * old chargebacks stay unlinkable. There is nothing to backfill from: the reference only ever
     * existed in the event.
     */
    val paymentRef: String? = null,
)

