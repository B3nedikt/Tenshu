check_size() { # $1 = png
  local dims
  dims="$(sips -g pixelWidth -g pixelHeight "$1" | awk '/pixelWidth/{w=$2} /pixelHeight/{h=$2} END{print w "x" h}')"
  [ "$dims" = "$SIZE" ] || { log "WRONG SIZE — $1 is $dims, expected $SIZE"; return 1; }
}

# Same warning as the iOS script's, against store/<app>/screens.json → android.captured.
check_screens() { # $1 = app, $2 = list of captured names
  python3 - "$ROOT/store/$1/screens.json" "$2" "$OFFLINE" "$1" "$([ "$SET" = support ] && echo android || echo landing)" <<'PY'
import json, os, sys
listed_path, got_path, offline, app, block = sys.argv[1:6]
listed = json.load(open(listed_path))[block]["captured"]
expected = {n for n, e in listed.items() if not (offline == "1" and e.get("devLabOnly"))}
got = set(open(got_path).read().split()) if os.path.exists(got_path) else set()
for name in sorted(got - set(listed)):
    print(f"store-screenshots-android: WARNING — {app}: captured {name}, which store/{app}/screens.json {block}.captured does not list")
for name in sorted(expected - got):
    print(f"store-screenshots-android: WARNING — {app}: store/{app}/screens.json {block}.captured lists {name}, but this run did not capture it")
PY
}

FAILED=0
for APPEARANCE in "${APPEARANCE_LIST[@]}"; do
  log "$APPEARANCE ($LANG_CODE) — fresh install of Control, Drive and ${APPS[*]}"
  # Every Tenshu app the AVD carries goes: a stale peer would be a schema peer of the new realm.
  for pkg in $(adb shell pm list packages | tr -d '\r' | sed -n 's/^package://p' | grep -E '^(app|com)\.tenshu\.'); do
    adb uninstall "$pkg" >/dev/null || true
  done
  adb shell cmd uimode night "$([ "$APPEARANCE" = dark ] && echo yes || echo no)" >/dev/null
  adb install -r "$CONTROL_APK" >/dev/null
  adb install -r "$DRIVE_APK" >/dev/null
  [ "$SET" = support ] || adb install -r "$PHOTOS_APK" >/dev/null
  for a in "${SIDE_APPS[@]}"; do
    if walks "$a" && [ "$APPEARANCE" = light ]; then adb install -r "$(apk_of "$a")" >/dev/null; fi
  done
  # The camera, as a user allows it when Add a device opens on "Scan a code": no dialog over the
  # walk. Notifications stay at the default (not granted), so no icon reaches the status bar.
  adb shell pm grant app.tenshu.control.android android.permission.CAMERA
  # The language: each app's own locale, never the system's (the picker and Health Connect stay
  # English). Set before any app's first launch; checked, because a silent no-op would capture an
  # English set into the German folder.
  if [ "$LANG_CODE" != en ]; then
    for pkg in $(adb shell pm list packages | tr -d '\r' | sed -n 's/^package://p' | grep -E '^(app|com)\.tenshu\.'); do
      adb shell cmd locale set-app-locales "$pkg" --locales "$LANG_CODE-DE" >/dev/null
      # Captured first: under pipefail a `| grep -q` that exits early can fail adb with SIGPIPE.
      locales="$(adb shell cmd locale get-app-locales "$pkg" | tr -d '\r')"
      case "$locales" in *"$LANG_CODE-DE"*) ;; *) die "could not set $pkg's locale to $LANG_CODE-DE ($locales)" ;; esac
    done
  fi

  results="$WORK/$LANG_CODE-$APPEARANCE"
  [ "$SET" = support ] || results="$WORK/$SET-$LANG_CODE-$APPEARANCE"
  rm -rf "$results"; mkdir -p "$results"
  args=()
  poller=""
  if [ "$OFFLINE" = 0 ]; then
    email="alex.$(python3 -c 'import time; n=int(time.time()*10); s=""
while n: n, r = divmod(n, 36); s = "0123456789abcdefghijklmnopqrstuvwxyz"[r] + s
print(s)')@example.com"
    otp_file="$results/otp"
    log "$APPEARANCE — signing up $email on the dev lab"
    otp_poller "$email" "$otp_file" &
    poller=$!
    args=(--email "$email" --otp-file "$otp_file")
  else
    args=(--offline)
  fi

  # Home: a desktop Tenshu Hub on the dev lab, its simulated devices announced under ordinary names
  # ("Simulated light" reads as a fake on a listing), provisioned in a data dir of this run and armed
  # for pairing; Control's walk pairs it from its printed URI, as a user does from the label (§8.2).
  if walks home && [ "$APPEARANCE" = light ]; then
    hub_dir="$results/hub"
    rm -rf "$hub_dir"; mkdir -p "$hub_dir"
    hub_args=(--data-dir "$hub_dir/data" --relay-url "$DEV_RELAY" --name "Tenshu Hub")
    "$HUB_BIN" provision "${hub_args[@]}" > "$hub_dir/provision.log" 2>&1 \
      || { tail -20 "$hub_dir/provision.log"; die "the hub did not provision (log: $hub_dir/provision.log)"; }
    cp "$hub_dir/data/pairing-uri.txt" "$hub_dir/pairing-uri.txt"
    "$HUB_BIN" run "${hub_args[@]}" --simulated-devices \
      --simulated-device-name "light=Living room lamp" \
      --simulated-device-name "sensor=Bedroom climate" \
      --simulated-device-name "bridge=Device bridge" \
      > "$hub_dir/run.log" 2>&1 &
    HUB_PID=$!
    args+=(--hub-uri-file "$hub_dir/pairing-uri.txt")
  fi

  ok=1
  python3 scripts/lib/android_shots.py control --lang "$LANG_CODE" --out "$results/control" "${args[@]}" > "$results/control.captured" || ok=0
  if [ -n "$poller" ]; then
    kill "$poller" 2>/dev/null || true
    wait "$poller" 2>/dev/null || true
    rm -f "$otp_file"
  fi
  # ⚠⚠ Control must trust the dev lab's issuer, or every client renders the realm as unfunded
  # ("Not syncing — this device has no storage plan") while Control's own Services card says Free.
  # Control prints its trusted
  # publishers at start-up (initEntitlementStorage); refuse the run here rather than capture banners.
# ⚠ It matches the publisher ID only, not the key: an APK built before the dev lab's issuer was
# re-keyed (a `-replace` rebuild) passes this check and still shows the realm as unfunded.
  if [ "$ok" = 1 ] && [ "$OFFLINE" = 0 ]; then
    # `|| true`: under pipefail a grep with no match would exit the script here, before the log below.
    trust="$(adb logcat -d -s System.out:I | grep 'Entitlement trust:' | tail -1 || true)"
    case "$trust" in
      *"build-configured: ${DEV_ISSUER%%:*}"*) ;;
      *) log "Control does not trust ${DEV_ISSUER%%:*} (start-up line: ${trust:-none}) — rebuild without --skip-build"; ok=0 ;;
    esac
  fi
  if [ "$ok" = 1 ] && walks drive; then
    drive_args=(--fixture "$FIXTURE" --set "$SET")
    [ "$SET" != promo ] || drive_args+=(--upload "$UPLOAD_DIR")
    [ -z "$BACKUP_DIR" ] || drive_args+=(--backup "$BACKUP_DIR")
    [ "$OFFLINE" = 0 ] || drive_args=(--offline)
    python3 scripts/lib/android_shots.py drive --lang "$LANG_CODE" --out "$results/drive" "${drive_args[@]}" \
      > "$results/drive.captured" || ok=0
  fi
  # Photos reads the realm the landing Drive walk filled, so it runs after it.
  if [ "$ok" = 1 ] && wants photos; then
    python3 scripts/lib/android_shots.py photos --lang "$LANG_CODE" --out "$results/photos" --set "$SET" \
      ${PROMO_CONFIG:+--promo-config "$PROMO_CONFIG"} \
      > "$results/photos.captured" || ok=0
  fi
  # Fit, Calendar and Contacts each join the realm Control made, through Control (Binder), and
  # import their fixture through their own shipping import (store-screenshots.md §8). Contacts goes
  # first: the name its You screen types is the realm owner's, which Fit's Profile shows too.
  for a in contacts calendar fit timeline; do
    if [ "$ok" = 1 ] && walks "$a" && [ "$APPEARANCE" = light ]; then
      python3 scripts/lib/android_shots.py "$a" --lang "$LANG_CODE" --out "$results/$a" --fixture "$ROOT/build/store/fixture/$a" \
        > "$results/$a.captured" || ok=0
    fi
  done
  # Maps reads the places Timeline's import made; Mia the rows Drive's and Calendar's walks made.
  for a in maps home mia; do
    if [ "$ok" = 1 ] && walks "$a" && [ "$APPEARANCE" = light ]; then
      python3 scripts/lib/android_shots.py "$a" --lang "$LANG_CODE" --out "$results/$a" \
        > "$results/$a.captured" || ok=0
    fi
  done
  stop_hub
  [ "$ok" = 1 ] || { FAILED=1; adb exec-out screencap -p > "$results/failure.png" || true; log "$APPEARANCE — the walk failed (last screen: $results/failure.png)"; continue; }

  for app in "${APPS[@]}"; do
    if light_only "$app" && [ "$APPEARANCE" != light ]; then
      log "$APPEARANCE — skipping $app (light only so far)"
      continue
    fi
    out="$ROOT/store/$app/screenshots/android/$DEVICE/$LANG_CODE"
    [ "$APPEARANCE" = light ] || out="$out/$APPEARANCE"
    mkdir -p "$out"
    for png in "$results/$app"/*.png; do
      check_size "$png" || FAILED=1
      cp "$png" "$out/"
      echo "  ${out#"$ROOT"/}/$(basename "$png")"
    done
    for mp4 in "$results/$app"/*.mp4; do   # the promo set's recordings
      [ -e "$mp4" ] || continue
      cp "$mp4" "$out/"
      echo "  ${out#"$ROOT"/}/$(basename "$mp4")"
    done
    # The promo set lists no screens anywhere: only the video reads it.
    [ "$SET" = promo ] || check_screens "$app" "$results/$app.captured"
  done
done

