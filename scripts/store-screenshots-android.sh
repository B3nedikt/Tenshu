#!/usr/bin/env bash
#
# Support-page screenshots for the Android apps (docs/how-to/store-screenshots.md §8) — the
# Android twin of scripts/store-screenshots.sh.
#
#   scripts/store-screenshots-android.sh [control] [drive] [fit] [calendar] [contacts] [timeline] [maps] [mia]
#                                        [--appearance light|dark|both] [--lang en|de]
#                                        [--avd NAME] [--skip-build] [--keep-emulator] [--offline]
#   scripts/store-screenshots-android.sh --set landing [drive] [photos] [--appearance …] [--lang en|de]
#   scripts/store-screenshots-android.sh --set promo --fixture-dir DIR --upload-dir DIR [--backup-dir DIR]
#                                        [--promo-config FILE] [--keep-emulator]
#
# Builds Control and Drive (debug, pointed at the dev lab), boots a Pixel 8 AVD read-only on its own
# port (`Pixel_8_Shots`, created on first use from an installed system image — see "The AVD" below), puts the status bar in demo mode (9:41, full battery and Wi-Fi, no mobile icon, no
# notifications), and per appearance: removes every Tenshu app, installs the two fresh, walks
# Control's onboarding, Drive's empty listing and — after uploading the store fixture through the
# app's own buttons — its filled one, by taps (scripts/lib/android_shots.py), and writes
#
#   store/<app>/screenshots/android/phone/en/NN-<screen>.png        light
#   store/<app>/screenshots/android/phone/en/dark/NN-<screen>.png   dark
#
# ⚠ Never committed: publish with scripts/store-publish.sh, as the iOS captures are.
#
# ⚠⚠ The AVD is never modified. `-read-only` puts every write of the session in a temporary
# overlay that is thrown away when the emulator exits, so the realm, the account's session and the
# recovery phrase of the run vanish with it, and the AVD the smoke gate uses is untouched. The
# dev-lab emulator (`tenshu_dev_lab`, port 5580) is refused: it holds a client that stays onboarded.
# The run never talks to any device but the emulator it booted (`emulator-$PORT`).
#
# The realm is a REAL one on the dev lab (tenshu.xyz — never production), signed up for the Free
# plan with a throwaway `alex.<base-36 time>@example.com`, the OTP read from the dev lab's mailbox
# (Keychain token, never printed), exactly as the iOS script does. Android has no runtime origin
# seam, so the four dev-lab settings are compiled in with -P flags (deploy-dev-lab-scaleway.md §10);
# they win over local.properties, which stays production's. `--offline` builds a production-pointed
# debug build and captures only the screens that need no account.
#
# `--set landing` is the landing page's content set (store-screenshots.md §9): a separate realm seeded
# from the stock-photo recipe store/fixtures/landing/manifest.json, Drive and Photos walked over it,
# written to store/<app>/screenshots/android/phonelanding/<lang>/ — a device of its own, so a landing
# capture never replaces a support-page one. Control is onboarded (the realm needs it) but not kept.
#
# `--set promo` is the promo video's own realm (store-screenshots.md §9, "The promo set"): the landing
# set's flow over a tree of the maintainer's own photos instead of the stock recipe — `--fixture-dir`,
# staged by store/fixtures/promo/stage_photos.py, never in git — plus screen recordings (`.mp4`, beside
# the captures in android/phonepromo/<lang>/): a photo from `--upload-dir` uploaded through + → Upload →
# Images, a share link, Control's recovery phrase, Synced Folders backing up `--backup-dir`, a scroll
# through Photos and, with `--promo-config`, an album's photo made a favourite. Published nowhere:
# the promo video, kept outside this tree, composes them.
#
# `fit`, `calendar`, `contacts` (store-screenshots.md §8, light and dev lab only): each app's APK is
# built and installed beside Control and Drive, its fixture generated by the iOS run's own generator
# (store/fixtures/<app>/), and its walk runs after Control's, over the realm Control made. Every
# datum enters through the app's shipping import — Contacts' .vcf import, Calendar's .ics import
# per calendar, Fit's Google Takeout file import — except Fit's daily figures, which a DEBUG-only
# seed writes into Health Connect for Fit's own Health Connect import to read back.
#
# `timeline`, `maps`, `mia` (store-screenshots.md §8.2, light and dev lab only): Timeline imports the iOS
# run's generated Google Timeline export as a Takeout zip through Settings → Import from Google Takeout;
# Maps shows the places that import made (it has no way of its own to make one), so `maps` walks
# Timeline too; Mia answers typed questions from Drive's and Calendar's rows, so `mia` walks both. A
# walk run only for its data is not copied out.
#
# `--lang de` captures the German set into …/<device>/de/: after each install every Tenshu app's own
# locale is set to de-DE (`cmd locale set-app-locales`) — German strings, German dates and numbers —
# while the system stays English, so the system picker and Health Connect's sheets the walk taps
# are never captured and keep their English labels. The walk still names every control in English;
# android_shots.py also accepts its German, read from the apps' values-de string resources. A screen
# the app has no German for stays English. Default `en`: the support pages show the English capture
# for a language that has none (generate.ts SHOT_FALLBACK_LANG).

set -euo pipefail

# One heavy build at a time on this machine (scripts/lib/gate-lock.sh).
# shellcheck source=scripts/lib/gate-lock.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/gate-lock.sh"
tenshu_gate_lock "$0" "$@"

ROOT="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
cd "$ROOT"

APPS=()
APPEARANCE_LIST=(light)
AVD="${TENSHU_SHOTS_AVD:-Pixel_8_Shots}"
PORT="${TENSHU_SHOTS_PORT:-5590}"
SKIP_BUILD=0
SET=support
KEEP_EMULATOR=0
FIXTURE_DIR=""
UPLOAD_DIR=""
BACKUP_DIR=""
PROMO_CONFIG=""
OFFLINE=0
LANG_CODE=en
while [ $# -gt 0 ]; do
  case "$1" in
    control|drive|photos|fit|calendar|contacts|timeline|maps|mia|home) APPS+=("$1") ;;
    --set)
      case "${2:-}" in
        support|landing|promo) SET="$2" ;;
        *) echo "store-screenshots-android: --set takes support, landing or promo" >&2; exit 2 ;;
      esac
      shift ;;
    --appearance)
      case "${2:-}" in
        light|dark) APPEARANCE_LIST=("$2") ;;
        both) APPEARANCE_LIST=(light dark) ;;
        *) echo "store-screenshots-android: --appearance takes light, dark or both" >&2; exit 2 ;;
      esac
      shift ;;
    --lang)
      case "${2:-}" in
        en|de) LANG_CODE="$2" ;;
        *) echo "store-screenshots-android: --lang takes en or de" >&2; exit 2 ;;
      esac
      shift ;;
    --avd) AVD="$2"; shift ;;
    --fixture-dir) FIXTURE_DIR="$(cd "$2" && pwd)"; shift ;;
    --upload-dir) UPLOAD_DIR="$(cd "$2" && pwd)"; shift ;;
    --backup-dir) BACKUP_DIR="$(cd "$2" && pwd)"; shift ;;
    --promo-config) PROMO_CONFIG="$(cd "$(dirname "$2")" && pwd)/$(basename "$2")"; shift ;;
    --skip-build) SKIP_BUILD=1 ;;
    --keep-emulator) KEEP_EMULATOR=1 ;;
    --offline) OFFLINE=1 ;;
    -h|--help) sed -n '2,69p' "$0"; exit 0 ;;
    *) echo "store-screenshots-android: unknown argument '$1'" >&2; exit 2 ;;
  esac
  shift
done
if [ "$SET" != support ]; then
  [ ${#APPS[@]} -gt 0 ] || APPS=(drive photos)
  for a in "${APPS[@]}"; do
    case "$a" in drive|photos) ;; *) echo "store-screenshots-android: the $SET set has drive and photos, not $a" >&2; exit 2 ;; esac
  done
  [ "$OFFLINE" = 0 ] || { echo "store-screenshots-android: the $SET set needs the dev lab (a funded realm takes the uploads)" >&2; exit 2; }
  if [ "$SET" = promo ]; then
    [ -d "$FIXTURE_DIR" ] && [ -d "$UPLOAD_DIR" ] \
      || { echo "store-screenshots-android: --set promo needs --fixture-dir and --upload-dir (store/fixtures/promo/stage_photos.py)" >&2; exit 2; }
    [ -z "$PROMO_CONFIG" ] || [ -f "$PROMO_CONFIG" ] \
      || { echo "store-screenshots-android: no --promo-config file $PROMO_CONFIG" >&2; exit 2; }
  fi
else
  [ ${#APPS[@]} -gt 0 ] || APPS=(control drive)
  for a in "${APPS[@]}"; do
    [ "$a" != photos ] || { echo "store-screenshots-android: photos has only the landing and promo sets (--set landing|promo)" >&2; exit 2; }
  done
fi
wants() { local a; for a in "${APPS[@]}"; do [ "$a" = "$1" ] && return 0; done; return 1; }
# The walks the run makes: the apps asked for, plus the ones whose data an asked-for app reads
# (store-screenshots.md §8.2). Maps shows Timeline's places; Mia answers from Drive's and Calendar's
# rows. A walk run only for its data is walked as usual, and its captures are not copied out.
WALKS=("${APPS[@]}")
walks() { local a; for a in "${WALKS[@]}"; do [ "$a" = "$1" ] && return 0; done; return 1; }
needs() { walks "$1" || WALKS+=("$1"); }
if [ "$SET" = support ]; then
  ! wants maps || needs timeline
  ! wants mia || { needs drive; needs calendar; }
fi
# Fit, Calendar, Contacts, Timeline, Maps and Mia: light only so far (store-screenshots.md §8) — no
# dark set has been looked at, as on iOS (§3a–§3g). Each needs the dev lab: its data reaches the realm
# Control made.
light_only() { case "$1" in fit|calendar|contacts|timeline|maps|mia|home) return 0 ;; esac; return 1; }
for a in "${WALKS[@]}"; do
  light_only "$a" || continue
  [ "$OFFLINE" = 0 ] || { echo "store-screenshots-android: $a needs the dev lab (its data goes into a synced realm) — drop --offline" >&2; exit 2; }
  case " ${APPEARANCE_LIST[*]} " in *" light "*) ;; *) echo "store-screenshots-android: $a runs in light only so far — drop --appearance dark" >&2; exit 2 ;; esac
done

DEVICE=phone              # the manifest's device segment: android/phone/<lang>/NN-screen
[ "$SET" = support ] || DEVICE=phone$SET       # android/phonelanding/<lang>/NN-screen (§9), …/phonepromo/…
SIZE=1080x2400            # a Pixel-class phone; every capture is checked against it
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Library/Android/sdk}}"
EMU="$SDK/emulator/emulator"
export ANDROID_SERIAL="emulator-$PORT"   # every adb call below, and the driver's, goes here only
WORK="$ROOT/build/store-shots/android"
mkdir -p "$WORK"

log() { echo "store-screenshots-android: $*"; }
die() { echo "store-screenshots-android: $*" >&2; exit 1; }

# ── The AVD ──────────────────────────────────────────────────────────────────
# ⚠⚠ A hardware profile WITH rounded display corners and a display cutout (store-screenshots.md §8).
# On a profile without them (the smoke gate's `Medium_Phone`) Android draws the status-bar clock ~2 %
# from the left edge, and the landing carousel's rounded phone frame clips it. On the Pixel 8 profile
# the system insets the status bar itself (corner radius 104 px, a punch-hole cutout), exactly as on
# the phone — and the screen is still 1080 × 2400, so every key and layout stays. The checks after
# the boot refuse an AVD whose display reports no rounded corners.
[ -x "$EMU" ] || die "no emulator at $EMU (set ANDROID_HOME)"
[ "$AVD" != tenshu_dev_lab ] || die "tenshu_dev_lab is the dev-lab client's own emulator — pass another --avd"
[ "$PORT" != 5580 ] || die "port 5580 belongs to the dev-lab emulator"
SHOTS_AVD=Pixel_8_Shots
# The system image the AVD is made from: the smoke gate's (already installed), no download.
SHOTS_IMAGE="${TENSHU_SHOTS_IMAGE:-system-images/android-37.2/google_apis_playstore_ps16k/arm64-v8a/}"
config="$HOME/.android/avd/$AVD.avd/config.ini"
if [ "$AVD" = "$SHOTS_AVD" ] && [ ! -f "$config" ]; then
  # Created by hand rather than by avdmanager (not every SDK here has cmdline-tools): the Pixel 8
  # device and skin — the skin carries the cutout and the corner mask the emulator hands the guest.
  [ -d "$SDK/$SHOTS_IMAGE" ] || die "no system image $SHOTS_IMAGE (sdkmanager --install, or set TENSHU_SHOTS_IMAGE)"
  [ -d "$SDK/skins/pixel_8" ] || die "no pixel_8 skin under $SDK/skins (install the emulator's device skins)"
  avd_dir="$HOME/.android/avd/$SHOTS_AVD.avd"
  log "creating AVD $SHOTS_AVD (Pixel 8 profile, $SHOTS_IMAGE)…"
  mkdir -p "$avd_dir"
  target="$(echo "$SHOTS_IMAGE" | cut -d/ -f2)"
  tag="$(echo "$SHOTS_IMAGE" | cut -d/ -f3)"
  cat > "$avd_dir/config.ini" <<CFG
AvdId=$SHOTS_AVD
avd.ini.displayname=Pixel 8 (store shots)
avd.ini.encoding=UTF-8
abi.type=arm64-v8a
disk.dataPartition.size=6G
hw.cpu.arch=arm64
hw.cpu.ncore=4
hw.device.manufacturer=Google
hw.device.name=pixel_8
hw.gpu.enabled=yes
hw.gpu.mode=auto
hw.initialOrientation=portrait
hw.keyboard=yes
hw.lcd.density=420
hw.lcd.height=2400
hw.lcd.width=1080
hw.mainKeys=no
hw.ramSize=2048
hw.sdCard=yes
image.sysdir.1=$SHOTS_IMAGE
sdcard.size=512M
showDeviceFrame=yes
skin.dynamic=no
skin.name=pixel_8
skin.path=$SDK/skins/pixel_8
tag.id=${tag%%_ps16k}
target=$target
CFG
  printf 'avd.ini.encoding=UTF-8\npath=%s\npath.rel=avd/%s.avd\ntarget=%s\n' \
    "$avd_dir" "$SHOTS_AVD" "$target" > "$HOME/.android/avd/$SHOTS_AVD.ini"
  # One plain boot makes the userdata image a `-read-only` boot then overlays; nothing else is kept.
  "$EMU" -avd "$SHOTS_AVD" -port "$PORT" -no-window -no-audio -no-boot-anim -no-snapshot \
    -gpu swiftshader_indirect > "$WORK/emulator-init.log" 2>&1 &
  init_pid=$!
  deadline=$(( $(date +%s) + 300 ))
  until [ "$(adb shell getprop sys.boot_completed 2>/dev/null | tr -d '\r')" = 1 ]; do
    [ "$(date +%s)" -lt "$deadline" ] || { kill "$init_pid" 2>/dev/null; die "the new AVD did not boot (log: $WORK/emulator-init.log)"; }
    sleep 3
  done
  sleep 10
  adb emu kill >/dev/null 2>&1 || kill "$init_pid" 2>/dev/null || true
  wait "$init_pid" 2>/dev/null || true
  # adb lists a killed emulator for a few seconds more; the check below would take it for another run.
  for _ in $(seq 1 30); do
    adb devices | awk 'NR>1{print $1}' | grep -qx "$ANDROID_SERIAL" || break
    sleep 1
  done
fi
[ -f "$config" ] || die "no AVD '$AVD' (~/.android/avd) — pass --avd with a 1080x2400 phone AVD"
avd_size="$(awk -F= '$1=="hw.lcd.width"{w=$2} $1=="hw.lcd.height"{h=$2} END{print w "x" h}' "$config")"
[ "$avd_size" = "$SIZE" ] || die "AVD '$AVD' is $avd_size, the support pages' Android captures are $SIZE"
if adb devices | awk 'NR>1{print $1}' | grep -qx "$ANDROID_SERIAL"; then
  die "$ANDROID_SERIAL is already attached — another run? Pass TENSHU_SHOTS_PORT=<even port>"
fi

# ── The dev lab ──────────────────────────────────────────────────────────────
# Same four settings and the same mailbox as scripts/store-screenshots.sh §"The dev lab".
DEV_RELAY="${TENSHU_SHOTS_RELAY:-https://relay.tenshu.xyz}"
DEV_COMMERCE="${TENSHU_SHOTS_COMMERCE:-https://commerce.tenshu.xyz}"
DEV_MAIL="${TENSHU_SHOTS_MAIL:-https://mail.tenshu.xyz}"
DEV_ISSUER="${TENSHU_SHOTS_ISSUER:-tenshu.commerce.dev:N3wP7kIUUeU3nZFhF0Pi77g0eFKPuUIB6FWVPzp4aQI=}"

# The mailbox token, straight from the Keychain into curl's stdin config — never an argument, a
# variable of this shell, or a line of output.
mail_get() { # $1 = path under the mail host → body on stdout
  { printf 'header = "Authorization: Bearer %s"\n' \
      "$(security find-generic-password -a tenshu -s dev-mailpit-token -w)"; } \
    | curl -sf --max-time 15 -K - "$DEV_MAIL$1"
}

if [ "$OFFLINE" = 0 ]; then
  for url in "$DEV_RELAY/health" "$DEV_COMMERCE/health"; do
    curl -sf --max-time 15 -o /dev/null "$url" \
      || die "the dev lab is not answering ($url) — try again later, or pass --offline"
  done
  # Before the build: a relay that refuses this checkout's protocol fails every walk at its sign-up.
  # shellcheck source=scripts/lib/devlab-relay-protocol.sh
  . "$ROOT/scripts/lib/devlab-relay-protocol.sh"
  devlab_relay_protocol_ok "$ROOT" "$DEV_RELAY" || die "the dev lab's relay is behind (above)"
  security find-generic-password -a tenshu -s dev-mailpit-token >/dev/null 2>&1 \
    || die "no dev-mailpit-token in the Keychain (deploy-dev-lab-scaleway.md §10) — or pass --offline"
  mail_get "/api/v1/messages?limit=1" >/dev/null \
    || die "the dev lab's mailbox ($DEV_MAIL) refuses the Keychain token — or pass --offline"
fi

# Polls the mailbox for the OTP sent to $1 and writes the code (only) to $2.
otp_poller() { # $1 = address, $2 = output file
  local query deadline=$(( $(date +%s) + 300 )) code
  query="$(python3 -c 'import sys, urllib.parse; print(urllib.parse.quote("to:\"%s\"" % sys.argv[1]))' "$1")"
  while [ "$(date +%s)" -lt "$deadline" ]; do
    code="$(mail_get "/api/v1/search?query=$query&limit=1" | python3 -c '
import json, re, sys
try:
    msgs = json.load(sys.stdin).get("messages") or []
except ValueError:
    msgs = []
m = msgs and re.search(r"\b(\d{6})\b", msgs[0].get("Snippet", ""))
print(m.group(1) if m else "")' 2>/dev/null || true)"
    if [ -n "$code" ]; then
      (umask 077; echo "$code" > "$2.tmp" && mv "$2.tmp" "$2")
      return 0
    fi
    sleep 2
  done
  return 1
}

# ── Build ────────────────────────────────────────────────────────────────────
# ⚠ Both apps always: Drive needs Control. -P flags outrank local.properties and the environment
# (control-shared-proxy/build.gradle.kts `resolveProxyOrigin`), so a stray dev-lab line in
# local.properties cannot change what --offline builds, and this run leaves no line behind.
CONTROL_APK=control/build/outputs/apk/debug/control-debug.apk
DRIVE_APK=drive-android/build/outputs/apk/debug/drive-android-debug.apk
PHOTOS_APK=photos-android/build/outputs/apk/debug/photos-android-debug.apk
FIT_APK=fit-android/build/outputs/apk/debug/fit-android-debug.apk
CALENDAR_APK=calendar-android/build/outputs/apk/debug/calendar-android-debug.apk
CONTACTS_APK=contacts-android/build/outputs/apk/debug/contacts-android-debug.apk
# Fit, Calendar, Contacts, Timeline, Maps and Mia: each its own APK beside Control and Drive.
SIDE_APPS=(fit calendar contacts timeline maps mia home)
apk_of() { echo "$1-android/build/outputs/apk/debug/$1-android-debug.apk"; }
GRADLE_TASKS=(:control:assembleDebug :drive-android:assembleDebug)
[ "$SET" = support ] || GRADLE_TASKS+=(:photos-android:assembleDebug)
for a in "${SIDE_APPS[@]}"; do walks "$a" && GRADLE_TASKS+=(":$a-android:assembleDebug"); done
# Home's devices come from a Tenshu Hub: the desktop one, with its simulated devices (§8.2).
HUB_BIN=hub/build/install/tenshu-hub/bin/tenshu-hub
! walks home || GRADLE_TASKS+=(:hub:installDist)
if [ "$SKIP_BUILD" = 0 ]; then
  props=()
  if [ "$OFFLINE" = 0 ]; then
    props=(-Ptenshu.relayUrl="$DEV_RELAY" -Ptenshu.commerceUrl="$DEV_COMMERCE"
           -Ptenshu.billingMock=false -Ptenshu.extraIssuer="$DEV_ISSUER")
    # ⚠ Clients and relay ship together (key-derived device ids came with no protocol bump), and
    # the dev lab runs recent master: a checkout behind it builds a client the relay refuses — a
    # 401 on the first push after sign-up, and a NEW-device code on "Show a code".
    if git fetch -q origin master 2>/dev/null; then
      behind="$(git rev-list --count HEAD..origin/master 2>/dev/null || echo 0)"
      [ "$behind" = 0 ] || log "⚠ this checkout is $behind commit(s) behind origin/master — the dev-lab relay may refuse the build (store-screenshots.md §8)"
    fi
  fi
  log "building ${GRADLE_TASKS[*]} (debug)…"
  ./gradlew "${GRADLE_TASKS[@]}" "${props[@]+"${props[@]}"}" \
    > "$WORK/build.log" 2>&1 \
    || { tail -40 "$WORK/build.log"; die "build failed (log: $WORK/build.log)"; }
fi
[ -f "$CONTROL_APK" ] && [ -f "$DRIVE_APK" ] || die "no APKs — run without --skip-build"
[ "$SET" = support ] || [ -f "$PHOTOS_APK" ] || die "no Photos APK — run without --skip-build"
for a in "${SIDE_APPS[@]}"; do
  ! walks "$a" || [ -f "$(apk_of "$a")" ] || die "no $a APK — run without --skip-build"
done
! walks home || [ -x "$HUB_BIN" ] || die "no hub build ($HUB_BIN) — run without --skip-build"


# ── The Drive fixture ────────────────────────────────────────────────────────
# The same tree the iOS run seeds (store/fixtures/drive/manifest.json, store-screenshots.md §3):
# every file drawn or fetched here, none in git. The walk pushes it to the emulator's Documents and
# uploads it through Drive's own + → Upload buttons and the system picker.
# The landing set seeds store/fixtures/landing/ instead: real stock photos, each fetched from its
# licensor's host and refused unless it hashes to its pin (§9).
FIXTURE_NAME=drive
[ "$SET" = support ] || FIXTURE_NAME=landing
FIXTURE="$ROOT/build/store/fixture/$FIXTURE_NAME"
[ "$SET" != promo ] || FIXTURE="$FIXTURE_DIR"   # staged by hand, never regenerated or removed here
if [ "$OFFLINE" = 0 ] && walks drive && [ "$SET" != promo ]; then
  rm -rf "$FIXTURE"
  python3 store/fixtures/generate.py "$FIXTURE_NAME" "$FIXTURE" || die "the $FIXTURE_NAME fixture did not build"
fi
# Fit, Calendar and Contacts: the very generators the iOS run uses (§3a–§3c), so both platforms show
# the same invented person — generated for the day of the run, never committed.
for a in fit calendar contacts timeline; do
  walks "$a" || continue
  rm -rf "$ROOT/build/store/fixture/$a"
  python3 "store/fixtures/$a/generate_$a.py" "$ROOT/build/store/fixture/$a" >/dev/null \
    || die "the $a fixture did not build"
done

# ── Emulator ─────────────────────────────────────────────────────────────────
log "booting AVD '$AVD' read-only as $ANDROID_SERIAL (headless)…"
"$EMU" -avd "$AVD" -port "$PORT" -read-only -no-window -no-audio -no-boot-anim -no-snapshot \
  -gpu swiftshader_indirect > "$WORK/emulator.log" 2>&1 &
EMU_PID=$!
HUB_PID=""
stop_hub() {
  [ -n "$HUB_PID" ] || return 0
  kill "$HUB_PID" 2>/dev/null || true
  wait "$HUB_PID" 2>/dev/null || true
  HUB_PID=""
}
stop_emulator() {
  stop_hub
  [ "$KEEP_EMULATOR" = 1 ] && { log "left $ANDROID_SERIAL running (--keep-emulator): adb -s $ANDROID_SERIAL emu kill"; return; }
  adb emu kill >/dev/null 2>&1 || kill "$EMU_PID" 2>/dev/null || true
  wait "$EMU_PID" 2>/dev/null || true
}
trap stop_emulator EXIT
deadline=$(( $(date +%s) + 300 ))
until [ "$(adb shell getprop sys.boot_completed 2>/dev/null | tr -d '\r')" = 1 ]; do
  [ "$(date +%s)" -lt "$deadline" ] || die "the emulator did not boot in 5 minutes (log: $WORK/emulator.log)"
  kill -0 "$EMU_PID" 2>/dev/null || die "the emulator exited (log: $WORK/emulator.log)"
  sleep 3
done
sleep 5

# The rounded corners are the point of the profile (above): a display without them puts the clock
# where a rounded frame clips it.
adb shell dumpsys display | grep -q 'RoundedCorner{position=TopLeft' \
  || die "AVD '$AVD' has no rounded display corners — the status bar would sit at the edge (use $SHOTS_AVD)"

# A large log ring: the image's UWB/NFC HALs crash-loop and fill the default one in minutes, and the
# walk reads Control's start-up line out of it (the issuer check after Control's walk).
adb logcat -G 16M >/dev/null 2>&1 || true

# The status bar of every capture. ⚠ On Android 17 demo mode's `notifications visible false` no
# longer hides notification icons, and `mobile show` keeps the real 3G icon and weak bars — so the
# mobile icon is hidden outright and the driver snoozes notifications before each capture.
