#!/usr/bin/env python3
"""The checks, the manifest and the Homebrew casks of a macOS direct release
(scripts/macos-direct-publish.sh; runbook docs/how-to/macos-release.md §7).

  macos_publish.py plan <release-dir> <base-url> <stage> [<published-date>]
      check a scripts/macos-release.sh output directory (ten notarized, stapled .dmg + SHA256SUMS)
      and write, into <stage>:
        objects.tsv         sha256 \\t path \\t key \\t filename \\t bytes   (one .dmg per line)
        macos-release.json  the NEW store/macos-release.json
      Nothing in the repo is written: the shell uploads the objects first and copies this in last.
  macos_publish.py check [<manifest>]
      fail unless the manifest (default store/macos-release.json) is well formed
  macos_publish.py urls [<manifest>]
      app \\t url \\t sha256 \\t bytes \\t filename, one line per app, for --verify
  macos_publish.py casks <manifest> <out-dir>
      write <out-dir>/Casks/tenshu-<app>.rb for the b3nedikt/homebrew-tenshu tap, from the manifest

The objects live in the Android release bucket at content-addressed keys, sha256/<hex>.dmg
(desktop-macos-distribution.md §2.7 "Hosting"): the version lives here, never in a URL.
"""
import datetime
import json
import os
import plistlib
import re
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
MANIFEST = "store/macos-release.json"
SCHEMA = 1
TEAM_ID = "752LWAZMKZ"
DMG_TYPE = "application/x-apple-diskimage"
CACHE_CONTROL = "public, max-age=31536000, immutable"
HEX64 = re.compile(r"^[0-9a-f]{64}$")
BASE = re.compile(r"^https://[a-z0-9.-]+/sha256/$")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
VERSION = re.compile(r"^\d+(\.\d+){1,2}$")
BUILD = re.compile(r"^\d{12}$")
ABOUT = ("Generated by scripts/macos-direct-publish.sh — do not edit. The notarized Developer ID .dmg "
         "of each desktop app, offered on tenshu.app and by the b3nedikt/homebrew-tenshu casks: url = "
         "base + sha256 + .dmg, served with Content-Disposition filename. One version for every app (D9). "
         "Schema: docs/how-to/macos-release.md §7.")

# Cask text. `desc` follows Homebrew's rules (no app name, no article, no "for macOS"); the wording is
# each app's store subtitle (store/<app>/en-US/subtitle.txt), Home's from its Play listing.
DESC = {
    "control": "Sync and encryption keys for the Tenshu apps",
    "drive": "Encrypted file storage",
    "maps": "Offline maps of your places",
    "home": "Smart-home devices and automations, encrypted",
    "calendar": "Private, encrypted calendar",
    "timeline": "Location history, kept private",
    "mia": "Ask questions about your Tenshu data",
    "photos": "Encrypted photo library",
    "fit": "Workouts and health, private",
    "contacts": "Encrypted contacts",
}
# Apps with a marketing page (web/apex/support-pages/appPages.ts APP_PAGES); the rest link the site.
APP_PAGES = {"control", "drive", "photos", "calendar", "contacts", "fit"}
# The casks' `livecheck` source: generated per app from store/macos-release.json by the website build
# (web/apex/support-pages/macosDownload.ts), so it names only a published version.
LIVECHECK = "https://tenshu.app/apps/{app}/download/macos.json"
# Homebrew's `depends_on macos:` symbol per LSMinimumSystemVersion major. ⚠ A new floor needs a row:
# the generator refuses an unknown one rather than guessing.
MACOS_SYMBOL = {"14": "sonoma", "15": "sequoia", "26": "tahoe"}


class Refusal(Exception):
    """Why a directory or manifest must not be published. The message is for the maintainer."""


def catalogue():
    """[(app, bundle 'TenshuPhotos', bundle id)] in install order, from scripts/lib/app-catalogue.sh."""
    script = ('source scripts/lib/app-catalogue.sh && for a in $TENSHU_APP_KEYS; do '
              'printf "%s\\t%s\\t%s\\n" "$a" "$(app_field "$a" desktopBundle)" "$(app_field "$a" iosBundle)"; done')
    out = subprocess.run(["bash", "-c", script], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    rows = []
    for line in out.splitlines():
        app, bundle, bundle_id = line.split("\t")
        if not bundle.endswith(".app"):
            raise Refusal(f"app-catalogue: {app}'s desktop bundle '{bundle}' is not a .app")
        rows.append((app, bundle[: -len(".app")], bundle_id))
    if len(rows) != len(DESC) or {r[0] for r in rows} != set(DESC):
        raise Refusal(f"app-catalogue lists {[r[0] for r in rows]}; this script knows {sorted(DESC)} — update DESC")
    return rows


def version_key(v: str):
    """1.0 and 1.0.0 compare equal (zero-padded), so neither reads as a downgrade of the other."""
    parts = [int(p) for p in v.split(".")]
    return tuple(parts + [0] * (3 - len(parts)))


def deployment_target() -> str:
    """gradle.properties tenshu.macosDeploymentTarget — what every bundle must declare (D10)."""
    with open(os.path.join(ROOT, "gradle.properties"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("tenshu.macosDeploymentTarget="):
                return line.split("=", 1)[1].strip()
    raise Refusal("no tenshu.macosDeploymentTarget in gradle.properties")


def sha256(path: str) -> str:
    out = subprocess.run(["shasum", "-a", "256", path], check=True, capture_output=True, text=True).stdout
    return out.split()[0]


def run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True)


def read_sums(path: str) -> dict:
    sums = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            parts = line.split(None, 1)
            if len(parts) != 2 or not HEX64.match(parts[0]):
                raise Refusal(f"{path}:{n} is not '<sha256>  <file>'")
            sums[parts[1].lstrip("*")] = parts[0]
    return sums


def inspect_dmg(dmg: str, bundle: str) -> dict:
    """Gatekeeper's verdict on the image, then the app inside it, read from a read-only mount."""
    staple = run(["xcrun", "stapler", "validate", dmg])
    if staple.returncode != 0:
        raise Refusal(f"{os.path.basename(dmg)}: no valid notarization ticket (stapler validate failed)")
    gk = run(["spctl", "-a", "-vv", "-t", "open", "--context", "context:primary-signature", dmg])
    if gk.returncode != 0 or "source=Notarized Developer ID" not in gk.stdout + gk.stderr:
        raise Refusal(f"{os.path.basename(dmg)}: Gatekeeper does not accept it as Notarized Developer ID:\n"
                      f"{(gk.stdout + gk.stderr).strip()}")
    mnt = tempfile.mkdtemp(prefix="macos-publish-mnt.")
    attach = run(["hdiutil", "attach", "-nobrowse", "-readonly", "-noautoopen", "-mountpoint", mnt, dmg])
    if attach.returncode != 0:
        os.rmdir(mnt)
        raise Refusal(f"{os.path.basename(dmg)}: hdiutil attach failed: {attach.stderr.strip()}")
    try:
        app = os.path.join(mnt, bundle + ".app")
        if not os.path.isdir(app):
            raise Refusal(f"{os.path.basename(dmg)} holds no {bundle}.app (has: {sorted(os.listdir(mnt))})")
        with open(os.path.join(app, "Contents", "Info.plist"), "rb") as f:
            info = plistlib.load(f)
        cs = run(["codesign", "-dv", "--verbose=2", app])
        text = cs.stdout + cs.stderr
        if f"TeamIdentifier={TEAM_ID}" not in text or "Authority=Developer ID Application:" not in text:
            raise Refusal(f"{bundle}.app is not signed with the team's Developer ID Application identity")
        return {
            "bundleId": info.get("CFBundleIdentifier"),
            "version": info.get("CFBundleShortVersionString"),
            "build": info.get("CFBundleVersion"),
            "minimumMacOS": info.get("LSMinimumSystemVersion"),
        }
    finally:
        run(["hdiutil", "detach", "-quiet", mnt])
        if os.path.isdir(mnt) and not os.listdir(mnt):
            os.rmdir(mnt)


def load(path: str) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def check_manifest(m: dict) -> None:
    def need(cond, what):
        if not cond:
            raise Refusal(f"manifest: {what}")
    need(isinstance(m, dict), "not a JSON object")
    for field in ("base", "version", "build", "minimumMacOS", "teamId", "published"):
        need(isinstance(m.get(field), str), f"{field} must be a string")
    need(isinstance(m.get("apps"), dict), "apps must be an object")
    need(m.get("schema") == SCHEMA, f"schema must be {SCHEMA}")
    need(BASE.match(m.get("base", "")), "base must be https://<host>/sha256/")
    need(VERSION.match(m.get("version", "")), "version must be x.y[.z]")
    need(BUILD.match(str(m.get("build", ""))), "build must be the 12-digit CFBundleVersion")
    need(VERSION.match(m.get("minimumMacOS", "")), "minimumMacOS must be x.y")
    need(m.get("teamId") == TEAM_ID, f"teamId must be {TEAM_ID}")
    need(DATE.match(m.get("published", "")), "published must be YYYY-MM-DD")
    apps = m.get("apps", {})
    need(list(apps) == [a for a, _, _ in catalogue()], "apps must be every catalogue app, in catalogue order")
    for app, e in apps.items():
        need(HEX64.match(e.get("sha256", "")), f"{app}.sha256")
        need(e.get("url") == m["base"] + e["sha256"] + ".dmg", f"{app}.url must be base + sha256 + .dmg")
        need(isinstance(e.get("bytes"), int) and e["bytes"] > 0, f"{app}.bytes")
        need(e.get("file") == f"{e.get('bundle')}-{m['version']}.dmg", f"{app}.file must be <bundle>-<version>.dmg")
        need(isinstance(e.get("bundleId"), str) and e["bundleId"], f"{app}.bundleId")


def plan(release_dir: str, base: str, stage: str, published: str) -> None:
    if not BASE.match(base):
        raise Refusal(f"base URL {base} is not https://<host>/sha256/")
    release_dir = os.path.realpath(release_dir)
    if os.path.basename(release_dir) != "macos-release":
        raise Refusal(f"{release_dir} is not a build/macos-release directory "
                      "(--pipeline-test output is never published)")
    sums_path = os.path.join(release_dir, "SHA256SUMS")
    if not os.path.isfile(sums_path):
        raise Refusal(f"no SHA256SUMS in {release_dir} — not a complete scripts/macos-release.sh run")
    sums = read_sums(sums_path)
    rows = catalogue()

    versions = {re.sub(r"\.dmg$", "", f).rsplit("-", 1)[-1] for f in sums}
    if len(versions) != 1:
        raise Refusal(f"SHA256SUMS names more than one version: {sorted(versions)} (D9: one version per release)")
    version = versions.pop()
    expected = {f"{b}-{version}.dmg" for _, b, _ in rows}
    if set(sums) != expected:
        raise Refusal(f"SHA256SUMS must list exactly the ten apps' .dmg. Missing: {sorted(expected - set(sums))}; "
                      f"extra: {sorted(set(sums) - expected)}")

    old = None
    if os.path.isfile(os.path.join(ROOT, MANIFEST)):
        old = load(os.path.join(ROOT, MANIFEST))
        check_manifest(old)
        if old["base"] != base:
            raise Refusal(f"{MANIFEST} names base {old['base']}, this run {base} — move the manifest deliberately")
        if version_key(version) < version_key(old["version"]):
            raise Refusal(f"version {version} is lower than the published {old['version']}")
        if version_key(version) == version_key(old["version"]) and version != old["version"]:
            raise Refusal(f"version {version} is the published {old['version']} spelled differently")

    apps, objects, builds, minimums = {}, [], set(), set()
    for app, bundle, bundle_id in rows:
        name = f"{bundle}-{version}.dmg"
        path = os.path.join(release_dir, name)
        got = sha256(path)
        if got != sums[name]:
            raise Refusal(f"{name} hashes to {got}, SHA256SUMS says {sums[name]}")
        info = inspect_dmg(path, bundle)
        if info["bundleId"] != bundle_id:
            raise Refusal(f"{bundle}.app is {info['bundleId']}, the catalogue says {bundle_id} (C4)")
        if info["version"] != version:
            raise Refusal(f"{bundle}.app is version {info['version']}, its file name says {version}")
        builds.add(info["build"])
        minimums.add(info["minimumMacOS"])
        if old and old["version"] == version and old["apps"][app]["sha256"] != got:
            raise Refusal(f"{version} is already published with other bytes for {app} — a version is published "
                          "once; bump it (the cask and every saved checksum name the old bytes)")
        size = os.path.getsize(path)
        apps[app] = {"bundle": bundle, "bundleId": bundle_id, "file": name, "url": base + got + ".dmg",
                     "sha256": got, "bytes": size}
        objects.append((got, path, f"sha256/{got}.dmg", name, size))
        print(f"  ok   {name}  {got}  ({info['build']})")
    if len(builds) != 1 or len(minimums) != 1:
        raise Refusal(f"the apps disagree on CFBundleVersion {sorted(builds)} or LSMinimumSystemVersion "
                      f"{sorted(minimums)} — not one run of scripts/macos-release.sh")
    target = deployment_target()
    if minimums != {target}:
        raise Refusal(f"the apps declare LSMinimumSystemVersion {minimums.pop()}, gradle.properties says {target} "
                      "(D10; jpackage's default is 10.13)")

    manifest = {
        "about": ABOUT, "schema": SCHEMA, "base": base, "version": version, "build": builds.pop(),
        "minimumMacOS": minimums.pop(), "arch": "arm64", "teamId": TEAM_ID,
        "published": old["published"] if old and old["version"] == version else published,
        "apps": apps,
    }
    check_manifest(manifest)
    os.makedirs(stage, exist_ok=True)
    with open(os.path.join(stage, "objects.tsv"), "w", encoding="utf-8") as f:
        for sha, path, key, name, size in objects:
            f.write(f"{sha}\t{path}\t{key}\t{name}\t{size}\n")
    with open(os.path.join(stage, "macos-release.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
        f.write("\n")


def rb(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def macos_symbol(minimum: str) -> str:
    major = minimum.split(".")[0]
    if major not in MACOS_SYMBOL:
        raise Refusal(f"no Homebrew macOS symbol for minimum {minimum} — add it to MACOS_SYMBOL")
    return MACOS_SYMBOL[major]


def cask(app: str, m: dict) -> str:
    e = m["apps"][app]
    title = "Tenshu " + app.capitalize()
    homepage = f"https://tenshu.app/apps/{app}" if app in APP_PAGES else "https://tenshu.app/"
    group = f"~/Library/Group Containers/{TEAM_ID}.app.tenshu.shared"
    lines = [
        f"# Generated by scripts/macos-direct-publish.sh --casks from store/macos-release.json — edit the",
        f"# generator (scripts/lib/macos_publish.py), not this file. desktop-macos-distribution.md §2.12.6.",
        f"cask {rb('tenshu-' + app)} do",
        f"  version {rb(m['version'])}",
        f"  sha256 {rb(e['sha256'])}",
        "",
        f"  url {rb(e['url'])}",
        f"  name {rb(title)}",
        f"  desc {rb(DESC[app])}",
        f"  homepage {rb(homepage)}",
        "",
        "  livecheck do",
        f"    url {rb(LIVECHECK.format(app=app))}",
        "    strategy :json do |json|",
        "      json[\"version\"]",
        "    end",
        "  end",
        "",
        "  depends_on arch: :arm64",
        f"  depends_on macos: :{macos_symbol(m['minimumMacOS'])}",
    ]
    if app != "control":
        # T3: never `depends_on cask: "tenshu-control"` — it would install a second Control over a
        # store copy.
        lines += ["", "  # No depends_on cask: \"tenshu-control\" — Control may come from the Mac App Store (§2.12.3 T3)."]
    lines += ["", f"  app {rb(e['bundle'] + '.app')}", ""]
    if app == "control":
        lines += [
            f"  uninstall launchctl: [\"app.tenshu.control\", \"app.tenshu.control.tray\"],",
            f"            quit:      {rb(e['bundleId'])},",
            "            delete:    [",
            "              \"~/Library/LaunchAgents/app.tenshu.control.plist\",",
            "              \"~/Library/LaunchAgents/app.tenshu.control.tray.plist\",",
            "            ]",
            "",
            "  # ⚠ zap removes this Mac's Tenshu store, device identity and every app's settings.",
            "  zap script: {",
            "        executable:   \"/usr/bin/security\",",
            "        args:         [\"delete-generic-password\", \"-s\", \"app.tenshu.control.desktop.master-key-store\"],",
            "        must_succeed: false,",
            "      },",
            "      trash:  [",
            "        \"~/Library/Application Support/TenshuControl\",",
            f"        {rb(group)},",
            "      ]",
        ]
    else:
        lines += [
            f"  uninstall quit: {rb(e['bundleId'])}",
            "",
            f"  zap trash: {rb(group + '/app.tenshu.' + app + '.desktop')}",
            "",
            "  caveats <<~EOS",
            f"    {title} needs Tenshu Control, from the Mac App Store or:",
            "      brew install --cask b3nedikt/tenshu/tenshu-control",
            "  EOS",
        ]
    lines.append("end")
    return "\n".join(lines) + "\n"


def write_casks(manifest_path: str, out: str) -> None:
    m = load(manifest_path)
    check_manifest(m)
    casks = os.path.join(out, "Casks")
    os.makedirs(casks, exist_ok=True)
    for app in m["apps"]:
        with open(os.path.join(casks, f"tenshu-{app}.rb"), "w", encoding="utf-8") as f:
            f.write(cask(app, m))
    print(f"wrote {len(m['apps'])} casks to {casks}")


def main(argv) -> int:
    try:
        if len(argv) >= 4 and argv[0] == "plan":
            published = argv[4] if len(argv) > 4 else datetime.date.today().isoformat()
            plan(argv[1], argv[2], argv[3], published)
        elif argv and argv[0] in ("check", "urls"):
            path = argv[1] if len(argv) > 1 else os.path.join(ROOT, MANIFEST)
            m = load(path)
            check_manifest(m)
            if argv[0] == "urls":
                for app, e in m["apps"].items():
                    print(f"{app}\t{e['url']}\t{e['sha256']}\t{e['bytes']}\t{e['file']}")
        elif len(argv) == 3 and argv[0] == "casks":
            write_casks(argv[1], argv[2])
        else:
            print(__doc__, file=sys.stderr)
            return 2
    except Refusal as r:
        print(f"macos-direct-publish: REFUSED — {r}", file=sys.stderr)
        return 1
    except FileNotFoundError as e:
        print(f"macos-direct-publish: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
