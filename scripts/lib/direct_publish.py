#!/usr/bin/env python3
"""The checks and the manifest of publishing a direct release (scripts/android-direct-publish.sh).

  direct_publish.py plan <release-dir> <base-url> <stage> [<published-date>]
      check a `android-release.sh --direct` output directory and write, into <stage>:
        objects.tsv           sha256 \\t path \\t key \\t filename \\t bytes   (one APK per line)
        android-release.json  the NEW store/android-release.json (old entries for other apps kept)
      Nothing in the repo is written: the shell uploads the objects first and copies this in last.
  direct_publish.py check [<manifest>]
      fail unless the committed store/android-release.json is well formed (default path)
  direct_publish.py urls [<manifest>]
      app \\t url \\t sha256 \\t bytes \\t filename, one line per app, for --verify

The manifest's schema is documented in docs/how-to/android-release.md, "Publishing a direct release";
the website's download pages read it (android-direct-apk-distribution.md Phase 1 item 5).
"""
import datetime
import json
import os
import re
import subprocess
import sys
import zipfile

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import direct_release  # noqa: E402

ROOT = direct_release.ROOT
MANIFEST = "store/android-release.json"
SCHEMA = 1
# One sequence with android-release.sh's ALL_APPS (a test keeps the two in step).
APPS = ("control", "drive", "maps", "timeline", "calendar", "contacts", "fit", "photos", "home", "mia")
APK_TYPE = "application/vnd.android.package-archive"
CACHE_CONTROL = "public, max-age=31536000, immutable"
HEX64 = re.compile(r"^[0-9a-f]{64}$")
BASE = re.compile(r"^https://[a-z0-9.-]+/sha256/$")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
ABOUT = ("Generated by scripts/android-direct-publish.sh — do not edit. The Android APKs offered on "
         "tenshu.app outside Google Play, one entry per app: url = base + sha256 + .apk, served with "
         "Content-Disposition filename. Every APK is signed by signingCertSha256, the side-channel key "
         "pinned in FirstPartySigning (android-direct-apk-distribution.md; schema: "
         "docs/how-to/android-release.md \"Publishing a direct release\").")


class Refusal(Exception):
    """Why a directory or manifest must not be published. The message is for the maintainer."""


def filename(app: str, version_code: int) -> str:
    """The name the browser saves the download under (the object's Content-Disposition)."""
    return f"tenshu-{app}-{version_code}.apk"


def content_disposition(app: str, version_code: int) -> str:
    return f'attachment; filename="{filename(app, version_code)}"'


def _read(path: str) -> str:
    try:
        with open(path) as f:
            return f.read()
    except FileNotFoundError:
        raise Refusal(f"{path} is missing — is this an android-release.sh --direct output directory?")


def check_release_dir(release_dir: str, pinned: str | None, signer_of=None) -> dict:
    """Everything that must hold before one byte of `release_dir` is uploaded; returns release.json.

    `pinned` is FirstPartySigning's side-channel digest (None while the slot is empty). `signer_of`
    maps an APK path to its one signing certificate (apksigner, by default).
    """
    real = os.path.realpath(release_dir)
    # ⚠⚠ By name first: android-release.sh --allow-unpinned writes here, and its APKs are signed by a
    # key no Play-installed app admits. Refused whatever its contents claim.
    if "direct-unpinned" in real.split(os.sep) or os.path.basename(real).startswith("direct-unpinned"):
        raise Refusal(f"{release_dir} is an --allow-unpinned build: never published")
    if os.path.basename(real).endswith(".staging"):
        raise Refusal(f"{release_dir} is android-release.sh's staging directory: an unfinished build")
    if not pinned:
        raise Refusal("no side-channel key is pinned in FirstPartySigning.SIDE_CHANNEL_SIGNING_CERT_SHA256 — "
                      "an APK from this channel would be refused by every Play-installed app")
    if not direct_release.DIGEST.match(pinned):
        raise Refusal(f"the pinned digest {pinned!r} is malformed")

    try:
        release = json.loads(_read(os.path.join(release_dir, "release.json")))
    except json.JSONDecodeError as e:
        raise Refusal(f"release.json does not parse: {e}")
    cert_txt = _read(os.path.join(release_dir, "signing-cert-sha256.txt")).strip()
    sums_txt = _read(os.path.join(release_dir, "SHA256SUMS"))

    problems = []
    cert = release.get("signingCertSha256")
    if cert != cert_txt:
        problems.append(f"release.json names signer {cert}, signing-cert-sha256.txt {cert_txt}")
    if cert != pinned:
        problems.append(f"release.json names signer {cert}, not the pinned side-channel key {pinned}")
    if release.get("abi") != direct_release.ABI:
        problems.append(f"abi is {release.get('abi')!r}, a direct release is {direct_release.ABI} only (D2)")
    version_code = release.get("versionCode")
    if not isinstance(version_code, int) or isinstance(version_code, bool) or version_code < 1:
        problems.append(f"versionCode {version_code!r} is not a positive whole number")
    # ≤ 64 and not blank: the website's validator (web/apex/support-pages/androidDownload.ts) refuses
    # anything else, and a refused manifest fails the website build.
    name = release.get("versionName")
    if not isinstance(name, str) or not name.strip() or len(name) > 64:
        problems.append(f"versionName {name!r} is missing, blank or over 64 characters")
    apps = release.get("apps")
    if not isinstance(apps, dict) or not apps:
        problems.append("release.json names no apps")
        apps = {}
    if problems:
        raise Refusal("; ".join(problems))

    sums = {}
    for line in sums_txt.splitlines():
        m = re.fullmatch(r"([0-9a-f]{64})  (\S+)", line)
        if not m:
            raise Refusal(f"SHA256SUMS has a line that is not `<sha256>  <file>`: {line!r}")
        sums[m.group(2)] = m.group(1)
    if set(sums) != {e.get("file") for e in apps.values()}:
        problems.append(f"SHA256SUMS names {sorted(sums)}, release.json {sorted(e.get('file') for e in apps.values())}")

    for app, e in sorted(apps.items()):
        if app not in APPS:
            problems.append(f"{app}: not a first-party app")
            continue
        if e.get("package") != f"app.tenshu.{app}.android":
            problems.append(f"{app}: package {e.get('package')!r}, expected app.tenshu.{app}.android")
        if e.get("file") != f"{app}-{version_code}.apk":
            problems.append(f"{app}: file {e.get('file')!r}, expected {app}-{version_code}.apk")
            continue
        path = os.path.join(release_dir, e["file"])
        if not os.path.isfile(path):
            problems.append(f"{app}: {e['file']} is missing")
            continue
        actual = direct_release.sha256_file(path)
        if actual != e.get("sha256") or actual != sums.get(e["file"]):
            problems.append(f"{app}: {e['file']} hashes to {actual}, release.json says {e.get('sha256')}"
                            f" and SHA256SUMS {sums.get(e['file'])} (changed since the build?)")
            continue
        if os.path.getsize(path) != e.get("bytes"):
            problems.append(f"{app}: {e['file']} is {os.path.getsize(path)} bytes, release.json says {e.get('bytes')}")
            continue
        # The ABI from the APK itself too, not only release.json's claim (D2).
        try:
            with zipfile.ZipFile(path) as z:
                abi = direct_release.abi_problems(z.namelist())
        except zipfile.BadZipFile:
            abi = ["not a zip file, so not an APK"]
        if abi:
            problems += [f"{app}: {p}" for p in abi]
            continue
        # ⚠⚠ The signer read back from the APK itself, not from release.json: the file the bucket
        # will serve is what a fresh install trusts (threat model T-DA-01/T-DA-04).
        try:
            signer = (signer_of or apk_signer)(path)
        except Refusal as r:
            problems.append(f"{app}: {r}")
            continue
        if signer != pinned:
            problems.append(f"{app}: {e['file']} is signed by {signer}, not by the pinned side-channel key {pinned}")
    if problems:
        raise Refusal("; ".join(problems))
    return release


def apk_signer(path: str) -> str:
    out = subprocess.run([direct_release.build_tool("apksigner"), "verify", "--print-certs", path],
                         capture_output=True, text=True)
    if out.returncode != 0:
        raise Refusal(f"apksigner refuses {os.path.basename(path)}: {(out.stderr or out.stdout).strip()}")
    found = direct_release.signers(out.stdout)
    if len(found) != 1:
        raise Refusal(f"{os.path.basename(path)} has {len(found)} signers, expected exactly one")
    return found[0]


def merge_manifest(old: dict | None, release: dict, base: str, published: str) -> dict:
    """The new store/android-release.json: this release's apps replaced, every other app's entry kept."""
    if not BASE.match(base):
        raise Refusal(f"base {base!r} is not https://<host>/sha256/")
    cert, abi, version_code = release["signingCertSha256"], release["abi"], release["versionCode"]
    old_apps = {}
    if old:
        check_manifest(old)
        if old["base"] != base:
            raise Refusal(f"{MANIFEST} names base {old['base']}, this run {base} — move the manifest deliberately")
        # ⚠⚠ A different key can never update a downloaded copy (Android refuses another signer), so a
        # manifest that changes key is a decision, never a side effect of a publish.
        if old["signingCertSha256"] != cert:
            raise Refusal(f"{MANIFEST} is signed by {old['signingCertSha256']}, this release by {cert}: "
                          "every downloaded copy would have to be uninstalled — move the manifest deliberately")
        old_apps = old["apps"]
    apps = dict(old_apps)
    for app, e in release["apps"].items():
        prev = old_apps.get(app)
        if prev is not None:
            # Android refuses to install a lower versionCode over a higher one, and an equal code with
            # other bytes is two different APKs under one version.
            if prev["versionCode"] > version_code:
                raise Refusal(f"{app}: {MANIFEST} offers versionCode {prev['versionCode']}, this release "
                              f"{version_code} — a download page must never go backwards")
            if prev["versionCode"] == version_code and prev["sha256"] != e["sha256"]:
                raise Refusal(f"{app}: versionCode {version_code} is already published with other bytes "
                              f"({prev['sha256']}) — build with a new --version-code")
        unchanged = prev is not None and prev["sha256"] == e["sha256"]
        apps[app] = {
            "package": e["package"],
            "versionCode": version_code,
            "versionName": release["versionName"],
            "abi": abi,
            "signingCertSha256": cert,
            "sha256": e["sha256"],
            "bytes": e["bytes"],
            "filename": filename(app, version_code),
            "url": f"{base}{e['sha256']}.apk",
            "published": prev["published"] if unchanged else published,
        }
    manifest = {
        "about": ABOUT,
        "schema": SCHEMA,
        "base": base,
        "abi": abi,
        "signingCertSha256": cert,
        "apps": {app: apps[app] for app in APPS if app in apps},
    }
    check_manifest(manifest)
    return manifest


def check_manifest(m: dict) -> None:
    """Raises Refusal unless `m` is a well-formed store/android-release.json."""
    problems = []
    if m.get("schema") != SCHEMA:
        raise Refusal(f"schema is {m.get('schema')!r}, this script writes {SCHEMA}")
    base, cert, abi = m.get("base"), m.get("signingCertSha256"), m.get("abi")
    if not isinstance(base, str) or not BASE.match(base):
        problems.append(f"base {base!r} is not https://<host>/sha256/")
    if not isinstance(cert, str) or not direct_release.DIGEST.match(cert):
        problems.append(f"signingCertSha256 {cert!r} is not a colon-separated SHA-256")
    if abi != direct_release.ABI:
        problems.append(f"abi {abi!r}, expected {direct_release.ABI}")
    apps = m.get("apps")
    if not isinstance(apps, dict) or not apps:
        problems.append("names no apps")
        apps = {}
    want = {"package", "versionCode", "versionName", "abi", "signingCertSha256", "sha256", "bytes",
            "filename", "url", "published"}
    for app, e in apps.items():
        if app not in APPS:
            problems.append(f"{app}: not a first-party app")
            continue
        if not isinstance(e, dict) or set(e) != want:
            problems.append(f"{app}: fields {sorted(e) if isinstance(e, dict) else e!r}, expected {sorted(want)}")
            continue
        vc = e["versionCode"]
        if not isinstance(vc, int) or isinstance(vc, bool) or vc < 1:
            problems.append(f"{app}: versionCode {vc!r}")
            continue
        sha = e["sha256"]
        checks = [
            (e["package"] == f"app.tenshu.{app}.android", f"package {e['package']!r}"),
            (isinstance(e["versionName"], str) and bool(e["versionName"].strip()) and len(e["versionName"]) <= 64,
             f"versionName {e['versionName']!r} is blank or over 64 characters"),
            (e["abi"] == abi, f"abi {e['abi']!r} differs from the manifest's"),
            (e["signingCertSha256"] == cert, "signingCertSha256 differs from the manifest's: one key signs every app"),
            (isinstance(sha, str) and bool(HEX64.match(sha)), f"sha256 {sha!r}"),
            (isinstance(e["bytes"], int) and not isinstance(e["bytes"], bool) and e["bytes"] > 0, f"bytes {e['bytes']!r}"),
            (e["filename"] == filename(app, vc), f"filename {e['filename']!r}, expected {filename(app, vc)}"),
            (e["url"] == f"{base}{sha}.apk", f"url {e['url']!r} is not base + sha256 + .apk"),
            (isinstance(e["published"], str) and bool(DATE.match(e["published"])), f"published {e['published']!r}"),
        ]
        problems += [f"{app}: {msg}" for ok, msg in checks if not ok]
    if problems:
        raise Refusal("; ".join(problems))


def render(manifest: dict) -> str:
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def plan(root: str, release_dir: str, base: str, stage: str, published: str | None = None,
         signer_of=None) -> dict:
    with open(os.path.join(root, direct_release.FIRST_PARTY_SIGNING)) as f:
        pinned = direct_release.pinned_digest(f.read())
    release = check_release_dir(release_dir, pinned, signer_of)
    path = os.path.join(root, MANIFEST)
    old = None
    if os.path.exists(path):
        with open(path) as f:
            old = json.load(f)
    published = published or datetime.datetime.now(datetime.timezone.utc).date().isoformat()
    manifest = merge_manifest(old, release, base, published)
    os.makedirs(stage, exist_ok=True)
    with open(os.path.join(stage, "objects.tsv"), "w") as f:
        for app, e in sorted(release["apps"].items()):
            f.write("\t".join([e["sha256"], os.path.abspath(os.path.join(release_dir, e["file"])),
                               f"sha256/{e['sha256']}.apk", filename(app, release["versionCode"]),
                               str(e["bytes"])]) + "\n")
    with open(os.path.join(stage, "android-release.json"), "w") as f:
        f.write(render(manifest))
    return manifest


def _load(path: str) -> dict:
    try:
        with open(path) as f:
            return json.load(f)
    except FileNotFoundError:
        raise Refusal(f"{path} does not exist: nothing is published yet")
    except json.JSONDecodeError as e:
        raise Refusal(f"{path} does not parse: {e}")


def main(argv: list[str]) -> int:
    if not argv:
        sys.exit(__doc__)
    cmd, args = argv[0], argv[1:]
    try:
        if cmd == "plan":
            release_dir, base, stage, *rest = args
            m = plan(ROOT, release_dir, base, stage, rest[0] if rest else None)
            print(f"direct-publish: {len(m['apps'])} app(s) in the manifest, signed by {m['signingCertSha256']}")
            return 0
        if cmd == "check":
            check_manifest(_load(args[0] if args else os.path.join(ROOT, MANIFEST)))
            return 0
        if cmd == "urls":
            m = _load(args[0] if args else os.path.join(ROOT, MANIFEST))
            check_manifest(m)
            for app, e in m["apps"].items():
                print("\t".join([app, e["url"], e["sha256"], str(e["bytes"]), e["filename"]]))
            return 0
    except Refusal as r:
        print(f"direct-publish: ✗ {r}", file=sys.stderr)
        return 1
    sys.exit(f"direct_publish: unknown command {cmd!r}\n{__doc__}")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
