#!/usr/bin/env python3
"""The web derivatives of the store screenshots: smaller WebP copies for the website
(docs/how-to/store-screenshots.md §7.1, store-presence-and-support-pages.md §3.3).

The published PNGs (1080 × 2400, 1320 × 2868, up to ~3 MB) stay what the App Store and fastlane
take. The website shows these instead: each PNG re-encoded as WebP at WIDTHS, each derivative
content-addressed by ITS OWN SHA-256 like every other object (`sha256/<hex>.webp`, so `immutable`
stays true even if a later cwebp encodes the same PNG differently), and recorded per app in
`store/<app>/screenshots.webp.json`, keyed by the SOURCE PNG's sha256:

    {"version": 1, "base": "https://assets.tenshu.app/sha256/", "derivatives": {
      "<png sha256>": [{"width": 540, "height": 1200, "sha256": "<webp sha256>", "bytes": 41234}, …]}}

⚠ A sidecar, not a field in screenshots.manifest.json, on purpose: the manifest is rewritten whole
by every publish (store-publish.sh), including by branches whose copy of the script predates this
file, and a field added there would be silently dropped by such a run. Keyed by the PNG's hash, the
sidecar is untouched by them; a manifest entry with no derivatives yet is simply shown as its PNG
(the web falls back), and the next publish from this script fills it in.

Run by scripts/store-publish.sh, never by hand:

    store_webp.py plan  <root> <stage> <base> <app>…   # what is missing; no network, no writes in the repo
    store_webp.py build <root> <stage> <base> <app>…   # encode what is missing into <stage>, stage the sidecars
    store_webp.py urls  <root> <app>                   # key, URL, bytes of every derivative (for --verify)

`plan` and `build` read each app's manifest from <stage>/<app>/ (the one this publish is about to
write) else from store/<app>/, and the local capture of a hash from <stage>/objects.tsv; a PNG
that is not captured locally is downloaded from R2 and its hash checked before it is encoded.
`build` writes <stage>/webp-objects.tsv (sha256, file) for the shell to upload and
<stage>/<app>/screenshots.webp.json for it to copy in once every object is up — objects first,
pointer last, as for the manifests.
"""
import hashlib
import json
import os
import shutil
import struct
import subprocess
import sys

# ⚠ Sized for the frames they fill (web/apex/src/landing/carousel/appCarousel.css): the carousel's
# phone is at most 75mm (≈ 283 CSS px, a ≈ 268 px screen) and a support page's step frame 15rem
# (≈ 228 px of screen), so 540 serves both at 1× AND 2× (536 px needed at 2×); 960 serves the
# phones' 3× (a 390 px phone's card is ≈ 190 px of screen, 570 px at 3×) and the narrow support
# column (17.5rem at 3×). Changing them leaves existing derivatives in place; a width that is new
# is filled in for every PNG on the next publish.
WIDTHS = (540, 960)
# Lossy WebP at q78 with sharp YUV keeps UI text crisp at 2× (checked against the 2× carousel
# render, 2026-10-18) at roughly 15–110 KB for 540 and 30–220 KB for 960, photo grids the largest.
CWEBP_ARGS = ["-quiet", "-q", "78", "-m", "6", "-sharp_yuv", "-metadata", "none"]
SIDECAR = "screenshots.webp.json"
ABOUT = (
    "Generated by scripts/store-publish.sh (scripts/lib/store_webp.py) — do not edit. The website's "
    "WebP copies of the store screenshots, keyed by the SOURCE PNG's sha256 (screenshots.manifest.json); "
    "each derivative's URL is base + its own sha256 + .webp. The images themselves are not in git."
)


def die(msg):
    sys.exit(f"store-publish: {msg}")


def webp_size(data):
    """(width, height) from a WebP file's header: lossy (VP8), lossless (VP8L) or extended (VP8X)."""
    if len(data) < 30 or data[:4] != b"RIFF" or data[8:12] != b"WEBP":
        raise ValueError("not a WebP file")
    chunk = data[12:16]
    if chunk == b"VP8X":
        w = 1 + int.from_bytes(data[24:27], "little")
        h = 1 + int.from_bytes(data[27:30], "little")
        return w, h
    if chunk == b"VP8 ":
        if data[23:26] != b"\x9d\x01\x2a":
            raise ValueError("bad VP8 start code")
        w, h = struct.unpack("<HH", data[26:30])
        return w & 0x3FFF, h & 0x3FFF
    if chunk == b"VP8L":
        if data[20] != 0x2F:
            raise ValueError("bad VP8L signature")
        bits = int.from_bytes(data[21:25], "little")
        return 1 + (bits & 0x3FFF), 1 + ((bits >> 14) & 0x3FFF)
    raise ValueError(f"unknown WebP chunk {chunk!r}")


def load_json(path, default):
    return json.load(open(path)) if os.path.exists(path) else default


def manifest_for(root, stage, app):
    staged = os.path.join(stage, app, "screenshots.manifest.json")
    path = staged if os.path.exists(staged) else os.path.join(root, "store", app, "screenshots.manifest.json")
    return load_json(path, None)


def wanted_widths(source_width):
    """The widths a PNG this wide gets: never an upscale, never a copy at its own size."""
    return [w for w in WIDTHS if w < source_width]


def plan_app(manifest, sidecar):
    """(kept derivatives by source sha, jobs) for one app.

    Kept: the sidecar's entries for PNGs the manifest still names, each limited to WIDTHS — a PNG
    the manifest no longer names is pruned, so republishing never grows the file. Jobs: every
    (sha, source width, source height, width) the manifest names that has no derivative yet."""
    sources = {}
    for entry in manifest.get("screens", {}).values():
        sources[entry["sha256"]] = (entry["width"], entry["height"])
    old = (sidecar or {}).get("derivatives", {})
    kept, jobs = {}, []
    for sha, (sw, sh) in sorted(sources.items()):
        have = {d["width"]: d for d in old.get(sha, []) if d.get("width") in WIDTHS}
        for w in wanted_widths(sw):
            if w not in have:
                jobs.append((sha, sw, sh, w))
        if have:
            kept[sha] = [have[w] for w in sorted(have)]
    return kept, jobs


def local_sources(stage):
    path = os.path.join(stage, "objects.tsv")
    found = {}
    if os.path.exists(path):
        for line in open(path):
            sha, _, full = line.rstrip("\n").partition("\t")
            if sha:
                found[sha] = full
    return found


def sidecar_text(base, derivatives):
    lines = [
        "{",
        f"  \"about\": {json.dumps(ABOUT, ensure_ascii=False)},",
        '  "version": 1,',
        f'  "base": {json.dumps(base)},',
        '  "derivatives": {',
    ]
    items = sorted(derivatives.items())
    for i, (sha, variants) in enumerate(items):
        body = json.dumps([{k: v[k] for k in ("width", "height", "sha256", "bytes")} for v in variants])
        lines.append(f"    {json.dumps(sha)}: {body}{',' if i < len(items) - 1 else ''}")
    lines += ["  }", "}", ""]
    return "\n".join(lines)


def plan_all(root, stage, base, apps):
    plans = {}
    for app in apps:
        manifest = manifest_for(root, stage, app)
        if manifest is None:
            continue
        sidecar = load_json(os.path.join(root, "store", app, SIDECAR), None)
        if sidecar and sidecar.get("base", base) != base:
            die(f"store/{app}/{SIDECAR} names base {sidecar['base']}, this run {base} — move it deliberately")
        plans[app] = plan_app(manifest, sidecar)
    return plans


def cmd_plan(root, stage, base, apps):
    plans = plan_all(root, stage, base, apps)
    local = local_sources(stage)
    total = 0
    for app, (kept, jobs) in plans.items():
        pngs = sorted({j[0] for j in jobs})
        print(f"store-publish: {app} — webp: {sum(len(v) for v in kept.values())} derivative(s) kept, "
              f"{len(jobs)} to make from {len(pngs)} PNG(s)")
        for sha in pngs:
            widths = ", ".join(f"w{j[3]}" for j in jobs if j[0] == sha)
            print(f"  {sha}.png → {widths}  ({'local capture' if sha in local else 'download from R2'})")
        total += len(jobs)
    with open(os.path.join(stage, "webp-jobs"), "w") as f:
        f.write(str(total))


def fetch_source(sha, base, local, cache):
    """The PNG with this hash: the local capture, else downloaded from R2 — hash-checked either way."""
    path = local.get(sha)
    if path is None:
        path = os.path.join(cache, f"{sha}.png")
        if not os.path.exists(path):
            # curl, as --verify uses: retries a dropped transfer, and R2's CDN refuses some default
            # client User-Agents (Python's urllib gets a 403).
            subprocess.run(["curl", "-sSf", "--retry", "4", "--retry-all-errors", "--max-time", "180",
                            "-o", path + ".part", f"{base}{sha}.png"], check=True)
            os.replace(path + ".part", path)
    data = open(path, "rb").read()
    if hashlib.sha256(data).hexdigest() != sha:
        die(f"{path} does not hash to {sha} — refusing to derive from it")
    return path


def encode(src, width, out):
    subprocess.run(["cwebp", *CWEBP_ARGS, "-resize", str(width), "0", src, "-o", out], check=True)
    data = open(out, "rb").read()
    w, h = webp_size(data)
    if w != width:
        die(f"cwebp made {w} px of {src}, asked for {width}")
    sha = hashlib.sha256(data).hexdigest()
    return {"width": w, "height": h, "sha256": sha, "bytes": len(data)}


def cmd_build(root, stage, base, apps):
    if shutil.which("cwebp") is None:
        die("'cwebp' is not on PATH (brew install webp) — docs/how-to/store-screenshots.md §7.1")
    plans = plan_all(root, stage, base, apps)
    local = local_sources(stage)
    cache = os.path.join(stage, "sources")
    out_dir = os.path.join(stage, "webp")
    os.makedirs(cache, exist_ok=True)
    os.makedirs(out_dir, exist_ok=True)
    made, objects = {}, {}
    for app, (kept, jobs) in plans.items():
        derivatives = {sha: list(v) for sha, v in kept.items()}
        for sha, _sw, _sh, width in jobs:
            if (sha, width) not in made:
                src = fetch_source(sha, base, local, cache)
                tmp = os.path.join(out_dir, f"{sha}.w{width}.webp")
                d = encode(src, width, tmp)
                final = os.path.join(out_dir, f"{d['sha256']}.webp")
                os.replace(tmp, final)
                objects[d["sha256"]] = final
                made[(sha, width)] = d
                print(f"  webp   {sha[:12]}… w{width} → {d['bytes']:>7} bytes")
            derivatives.setdefault(sha, []).append(made[(sha, width)])
            derivatives[sha].sort(key=lambda v: v["width"])
        os.makedirs(os.path.join(stage, app), exist_ok=True)
        if derivatives:
            open(os.path.join(stage, app, SIDECAR), "w").write(sidecar_text(base, derivatives))
    with open(os.path.join(stage, "webp-objects.tsv"), "w") as f:
        for sha, path in sorted(objects.items()):
            f.write(f"{sha}\t{path}\n")


def cmd_urls(root, app):
    sidecar = load_json(os.path.join(root, "store", app, SIDECAR), None)
    if sidecar is None:
        return
    for src, variants in sorted(sidecar["derivatives"].items()):
        for v in variants:
            print(f"webp/{src[:12]}/w{v['width']}\t{sidecar['base']}{v['sha256']}.webp\t{v['bytes']}")


def main(argv):
    if len(argv) >= 5 and argv[1] in ("plan", "build"):
        root, stage, base, apps = argv[2], argv[3], argv[4], argv[5:]
        (cmd_plan if argv[1] == "plan" else cmd_build)(root, stage, base, apps)
    elif len(argv) == 4 and argv[1] == "urls":
        cmd_urls(argv[2], argv[3])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
