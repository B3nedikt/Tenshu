#!/usr/bin/env python3
"""The checks and the manifest of a Windows direct release (scripts/windows-direct-publish.sh;
runbook docs/how-to/windows-release.md §3).

  windows_publish.py plan <release-dir> <base-url> <stage> [<published-date>]
      check a scripts/windows/windows-release.ps1 output directory (build/windows-release: one signed
      .msix per app, the public .cer, release.json, SHA256SUMS) and write, into <stage>:
        objects.tsv           sha256 \\t path \\t key \\t filename \\t bytes \\t content-type
        windows-release.json  the NEW store/windows-release.json
      Nothing in the repo is written: the shell uploads the objects first and copies this in last.
  windows_publish.py check [<manifest>]
      fail unless the manifest (default store/windows-release.json) is well formed
  windows_publish.py urls [<manifest>]
      name \\t url \\t sha256 \\t bytes \\t filename \\t content-type, one line per object, for --verify

The objects live in the release bucket at content-addressed keys, sha256/<hex>.msix and
sha256/<hex>.cer (deploy/cloudflare-releases): the version lives here, never in a URL. The packages
are built and signed on Windows; this runs on the Mac that holds the bucket key, so it re-checks
everything it can without Windows: the manifest inside each package, that the package carries a
signature naming the published certificate, and that the certificate's subject is the publisher
both peer gates were compiled for (desktop-windows-port.md §5.1, D6).
"""
import base64
import datetime
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
import zipfile

sys.dont_write_bytecode = True

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
MANIFEST = "store/windows-release.json"
SCHEMA = 1
MSIX_TYPE = "application/msix"
CER_TYPE = "application/pkix-cert"
CACHE_CONTROL = "public, max-age=31536000, immutable"
HEX64 = re.compile(r"^[0-9a-f]{64}$")
HEX40 = re.compile(r"^[0-9A-F]{40}$")
BASE = re.compile(r"^https://[a-z0-9.-]+/sha256/$")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
VERSION = re.compile(r"^\d+\.\d+\.\d+$")
PACKAGE_VERSION = re.compile(r"^\d+\.\d+\.\d+\.0$")
WINDOWS_VERSION = re.compile(r"^10\.0\.\d+\.\d+$")
PUBLISHER_ID = re.compile(r"^[0-9a-hjkmnp-tv-z]{13}$")
COMMIT = re.compile(r"^[0-9a-f]{40}$")
# The throwaway subject of scripts/windows/msix-test-cert.ps1; its key sits on developer disks.
LOCAL_TEST_PUBLISHER = "CN=Tenshu Local Test"
APPX_NS = "{http://schemas.microsoft.com/appx/manifest/foundation/windows10}"
ABOUT = ("Generated by scripts/windows-direct-publish.sh — do not edit. The signed MSIX of each Windows "
         "desktop app and the public certificate it is signed with, offered on tenshu.app: url = base + "
         "sha256 + extension, served with Content-Disposition filename. One version for every app (HR #9). "
         "Schema: docs/how-to/windows-release.md §3.")

# The apps with a Windows package, in install order (Control first), and what windows-release.ps1 builds for
# each: key -> (package base name, MSIX Identity/@Name). ⚠ W5 adds the other eight here, in
# windows-release.ps1's $apps and in web/apex/support-pages/windowsDownload.ts WINDOWS_PACKAGED together.
APPS = {
    "control": ("TenshuControl", "Tenshu.Control"),
    "drive": ("TenshuDrive", "Tenshu.Drive"),
}


class Refusal(Exception):
    """Why a directory or manifest must not be published. The message is for the maintainer."""


def publisher_id(publisher: str) -> str:
    """The half of a package family name after '_': what the peer gates pin. Same derivation as
    MsixPublisherId (:windows-helpers), gradle/desktop-msix.gradle.kts and windows-release.ps1."""
    alphabet = "0123456789abcdefghjkmnpqrstvwxyz"
    bits = int.from_bytes(hashlib.sha256(publisher.encode("utf-16-le")).digest()[:8], "big")
    out = []
    for group in range(13):
        shift = 59 - 5 * group
        v = (bits >> shift) & 0x1F if shift >= 0 else (bits << -shift) & 0x1F
        out.append(alphabet[v])
    return "".join(out)


if publisher_id("CN=Microsoft Corporation, O=Microsoft Corporation, L=Redmond, S=Washington, C=US") != "8wekyb3d8bbwe":
    raise SystemExit("windows_publish: publisher-id derivation is broken — it no longer reproduces Microsoft's id")


def version_key(v: str):
    return tuple(int(p) for p in v.split("."))


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git_head() -> str:
    return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, check=True, capture_output=True, text=True).stdout.strip()


def read_sums(path: str) -> dict:
    sums = {}
    with open(path, encoding="utf-8-sig") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            parts = line.split(None, 1)
            if len(parts) != 2 or not HEX64.match(parts[0]):
                raise Refusal(f"{path}:{n} is not '<sha256>  <file>'")
            sums[parts[1].lstrip("*")] = parts[0]
    return sums


def openssl(args, data: bytes = None) -> bytes:
    r = subprocess.run(["openssl"] + args, input=data, capture_output=True)
    if r.returncode != 0:
        raise Refusal(f"openssl {' '.join(args)} failed: {r.stderr.decode(errors='replace').strip()}")
    return r.stdout


def der_thumbprints(pem: bytes) -> set:
    """SHA-1 of every certificate in a PEM bundle, upper-case hex — the Windows thumbprint."""
    out = set()
    for block in re.findall(rb"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", pem, re.S):
        out.add(hashlib.sha1(base64.b64decode(b"".join(block.split()))).hexdigest().upper())
    return out


def read_certificate(path: str) -> dict:
    """Subject (RFC 2253), thumbprint and expiry of a DER certificate (what Export-Certificate writes)."""
    text = openssl(["x509", "-inform", "DER", "-in", path, "-noout", "-subject", "-nameopt", "RFC2253", "-enddate"]).decode()
    subject = re.search(r"^subject=\s*(.+)$", text, re.M)
    end = re.search(r"^notAfter=(.+)$", text, re.M)
    if not subject or not end:
        raise Refusal(f"{os.path.basename(path)}: not a certificate openssl can read")
    pem = openssl(["x509", "-inform", "DER", "-in", path, "-outform", "PEM"])
    (thumb,) = der_thumbprints(pem)
    not_after = datetime.datetime.strptime(end.group(1).strip().replace(" GMT", ""), "%b %d %H:%M:%S %Y").date()
    return {"subject": subject.group(1).strip(), "thumbprint": thumb, "notAfter": not_after.isoformat()}


def signature_thumbprints(p7x: bytes) -> set:
    """Every certificate an MSIX's AppxSignature.p7x carries (signer, chain, timestamp authority).
    ⚠ Presence, not a cryptographic verification: windows-release.ps1 checked the signer and the timestamp
    with Get-AuthenticodeSignature on Windows; this catches a package signed by another key or not at all."""
    if not p7x.startswith(b"PKCX"):
        raise Refusal("AppxSignature.p7x does not start with the PKCX magic")
    return der_thumbprints(openssl(["pkcs7", "-inform", "DER", "-print_certs"], p7x[4:]))


def inspect_msix(path: str) -> dict:
    """What the package says it is, read from the zip on any OS."""
    name = os.path.basename(path)
    try:
        with zipfile.ZipFile(path) as z:
            names = set(z.namelist())
            if "AppxManifest.xml" not in names:
                raise Refusal(f"{name}: no AppxManifest.xml — not an MSIX")
            if "AppxSignature.p7x" not in names:
                raise Refusal(f"{name}: UNSIGNED (no AppxSignature.p7x) — Windows will not install it")
            manifest = ET.fromstring(z.read("AppxManifest.xml"))
            p7x = z.read("AppxSignature.p7x")
    except zipfile.BadZipFile:
        raise Refusal(f"{name}: not a zip, so not an MSIX")
    identity = manifest.find(f"{APPX_NS}Identity")
    family = manifest.find(f"{APPX_NS}Dependencies/{APPX_NS}TargetDeviceFamily")
    if identity is None or family is None:
        raise Refusal(f"{name}: the manifest has no Identity or no TargetDeviceFamily")
    return {
        "name": identity.get("Name"),
        "publisher": identity.get("Publisher"),
        "version": identity.get("Version"),
        "arch": identity.get("ProcessorArchitecture"),
        "minimumWindows": family.get("MinVersion"),
        "signers": signature_thumbprints(p7x),
    }


def load(path: str) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def check_manifest(m: dict) -> None:
    def need(cond, what):
        if not cond:
            raise Refusal(f"manifest: {what}")
    need(isinstance(m, dict), "not a JSON object")
    for field in ("base", "version", "packageVersion", "minimumWindows", "publisher", "publisherId", "commit", "published"):
        need(isinstance(m.get(field), str), f"{field} must be a string")
    need(m.get("schema") == SCHEMA, f"schema must be {SCHEMA}")
    need(BASE.match(m["base"]), "base must be https://<host>/sha256/")
    need(VERSION.match(m["version"]), "version must be x.y.z")
    need(m["packageVersion"] == m["version"] + ".0", "packageVersion must be version + '.0'")
    need(m.get("arch") == "x64", "arch must be x64")
    need(WINDOWS_VERSION.match(m["minimumWindows"]), "minimumWindows must be 10.0.<build>.<rev>")
    need(m["publisher"].startswith("CN=") and m["publisher"] != LOCAL_TEST_PUBLISHER, "publisher must be a release CN=, never the local test one")
    need(m["publisherId"] == publisher_id(m["publisher"]), "publisherId must be the publisher's id")
    need(COMMIT.match(m["commit"]), "commit must be a 40-hex commit")
    need(DATE.match(m["published"]), "published must be YYYY-MM-DD")
    cert = m.get("certificate")
    need(isinstance(cert, dict), "certificate must be an object")
    need(HEX64.match(cert.get("sha256", "")), "certificate.sha256")
    need(cert.get("url") == m["base"] + cert["sha256"] + ".cer", "certificate.url must be base + sha256 + .cer")
    need(isinstance(cert.get("bytes"), int) and cert["bytes"] > 0, "certificate.bytes")
    need(HEX40.match(cert.get("thumbprint", "")), "certificate.thumbprint must be 40 upper-case hex")
    need(isinstance(cert.get("file"), str) and cert["file"].endswith(".cer"), "certificate.file must end .cer")
    need(DATE.match(cert.get("notAfter", "")), "certificate.notAfter must be YYYY-MM-DD")
    apps = m.get("apps")
    need(isinstance(apps, dict), "apps must be an object")
    need(list(apps) == list(APPS), f"apps must be {list(APPS)}, in that order")
    for app, e in apps.items():
        base, identity = APPS[app]
        need(e.get("identityName") == identity, f"{app}.identityName must be {identity}")
        need(HEX64.match(e.get("sha256", "")), f"{app}.sha256")
        need(e.get("url") == m["base"] + e["sha256"] + ".msix", f"{app}.url must be base + sha256 + .msix")
        need(isinstance(e.get("bytes"), int) and e["bytes"] > 0, f"{app}.bytes")
        need(e.get("file") == f"{base}-{m['version']}.msix", f"{app}.file must be {base}-<version>.msix")


def plan(release_dir: str, base: str, stage: str, published: str) -> None:
    if not BASE.match(base):
        raise Refusal(f"base URL {base} is not https://<host>/sha256/")
    release_dir = os.path.realpath(release_dir)
    if os.path.basename(release_dir) != "windows-release":
        raise Refusal(f"{release_dir} is not a build/windows-release directory")
    for need in ("SHA256SUMS", "release.json"):
        if not os.path.isfile(os.path.join(release_dir, need)):
            raise Refusal(f"no {need} in {release_dir} — not a complete windows-release.ps1 run")
    info = load(os.path.join(release_dir, "release.json"))
    if info.get("schema") != 1:
        raise Refusal("release.json: schema must be 1")
    if info.get("dirty"):
        raise Refusal("release.json says it was built from a dirty tree (-AllowDirty): never published")
    head = git_head()
    if info.get("commit") != head:
        raise Refusal(f"release.json was built from {info.get('commit')}, this checkout is at {head} — publish from the "
                      "commit that was built, so the manifest names the source of the bytes")
    version, package_version = info.get("version", ""), info.get("packageVersion", "")
    publisher = info.get("publisher", "")
    if not VERSION.match(version) or package_version != version + ".0":
        raise Refusal(f"release.json: version {version!r} / packageVersion {package_version!r} are not x.y.z / x.y.z.0")
    if not publisher.startswith("CN=") or publisher == LOCAL_TEST_PUBLISHER:
        raise Refusal(f"release.json: publisher {publisher!r} is not a release publisher")
    if info.get("publisherId") != publisher_id(publisher):
        raise Refusal(f"release.json: publisherId {info.get('publisherId')} is not {publisher}'s ({publisher_id(publisher)})")
    thumbprint = info.get("thumbprint", "")
    if not HEX40.match(thumbprint):
        raise Refusal("release.json: thumbprint must be 40 upper-case hex")

    sums = read_sums(os.path.join(release_dir, "SHA256SUMS"))
    cer_name = info.get("certificate", "")
    expected = {f"{b}-{version}.msix" for b, _ in APPS.values()} | {cer_name}
    if set(sums) != expected:
        raise Refusal(f"SHA256SUMS must list exactly {sorted(expected)}. Missing: {sorted(expected - set(sums))}; "
                      f"extra: {sorted(set(sums) - expected)}")
    for name, want in sums.items():
        got = sha256(os.path.join(release_dir, name))
        if got != want:
            raise Refusal(f"{name} hashes to {got}, SHA256SUMS says {want}")

    old = None
    if os.path.isfile(os.path.join(ROOT, MANIFEST)):
        old = load(os.path.join(ROOT, MANIFEST))
        check_manifest(old)
        if old["base"] != base:
            raise Refusal(f"{MANIFEST} names base {old['base']}, this run {base} — move the manifest deliberately")
        if version_key(version) < version_key(old["version"]):
            raise Refusal(f"version {version} is lower than the published {old['version']} — Windows refuses a downgrade over an install")
        if old["publisher"] != publisher:
            raise Refusal(f"the publisher changes from {old['publisher']} to {publisher}: a different package family, so it "
                          "installs BESIDE the old one and the peer gates of the two never admit each other. Deliberate? "
                          "Then move the manifest by hand and document the switch (windows-release.md §5)")

    cer_path = os.path.join(release_dir, cer_name)
    cert = read_certificate(cer_path)
    if cert["subject"] != publisher:
        raise Refusal(f"{cer_name} is '{cert['subject']}', the packages' publisher is '{publisher}'")
    if cert["thumbprint"] != thumbprint:
        raise Refusal(f"{cer_name} is certificate {cert['thumbprint']}, release.json says {thumbprint}")
    if cert["notAfter"] < published:
        raise Refusal(f"{cer_name} expired {cert['notAfter']}")

    apps, objects, minimums = {}, [], set()
    cer_sha = sums[cer_name]
    for app, (pkg, identity) in APPS.items():
        name = f"{pkg}-{version}.msix"
        path = os.path.join(release_dir, name)
        got = sums[name]
        m = inspect_msix(path)
        if m["name"] != identity:
            raise Refusal(f"{name}: Identity/@Name is {m['name']}, expected {identity} (the peer gate admits that name only)")
        if m["publisher"] != publisher:
            raise Refusal(f"{name}: Identity/@Publisher is {m['publisher']}, expected {publisher}")
        if m["version"] != package_version:
            raise Refusal(f"{name}: Identity/@Version is {m['version']}, expected {package_version}")
        if m["arch"] != "x64":
            raise Refusal(f"{name}: ProcessorArchitecture is {m['arch']}, expected x64")
        if thumbprint not in m["signers"]:
            raise Refusal(f"{name}: its signature does not carry certificate {thumbprint} — signed with another key")
        minimums.add(m["minimumWindows"])
        if old and old["version"] == version and old["apps"][app]["sha256"] != got:
            raise Refusal(f"{version} is already published with other bytes for {app} — a version is published once; bump it")
        size = os.path.getsize(path)
        apps[app] = {"identityName": identity, "file": name, "url": base + got + ".msix", "sha256": got, "bytes": size}
        objects.append((got, path, f"sha256/{got}.msix", name, size, MSIX_TYPE))
        print(f"  ok   {name}  {got}")
    if len(minimums) != 1:
        raise Refusal(f"the packages disagree on MinVersion: {sorted(minimums)}")
    cer_size = os.path.getsize(cer_path)
    objects.append((cer_sha, cer_path, f"sha256/{cer_sha}.cer", cer_name, cer_size, CER_TYPE))
    print(f"  ok   {cer_name}  {cer_sha}  ({cert['subject']}, {thumbprint}, until {cert['notAfter']})")

    manifest = {
        "about": ABOUT, "schema": SCHEMA, "base": base, "version": version, "packageVersion": package_version,
        "arch": "x64", "minimumWindows": minimums.pop(), "publisher": publisher, "publisherId": publisher_id(publisher),
        "certificate": {"file": cer_name, "url": base + cer_sha + ".cer", "sha256": cer_sha, "bytes": cer_size,
                        "thumbprint": thumbprint, "notAfter": cert["notAfter"]},
        "commit": head,
        "published": old["published"] if old and old["version"] == version else published,
        "apps": apps,
    }
    check_manifest(manifest)
    os.makedirs(stage, exist_ok=True)
    with open(os.path.join(stage, "objects.tsv"), "w", encoding="utf-8") as f:
        for sha, path, key, name, size, ctype in objects:
            f.write(f"{sha}\t{path}\t{key}\t{name}\t{size}\t{ctype}\n")
    with open(os.path.join(stage, "windows-release.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
        f.write("\n")


def urls(m: dict):
    rows = [(app, e["url"], e["sha256"], e["bytes"], e["file"], MSIX_TYPE) for app, e in m["apps"].items()]
    c = m["certificate"]
    rows.append(("certificate", c["url"], c["sha256"], c["bytes"], c["file"], CER_TYPE))
    return rows


def main(argv) -> int:
    try:
        if len(argv) >= 4 and argv[0] == "plan":
            published = argv[4] if len(argv) > 4 else datetime.date.today().isoformat()
            plan(argv[1], argv[2], argv[3], published)
        elif argv and argv[0] in ("check", "urls"):
            path = argv[1] if len(argv) > 1 else os.path.join(ROOT, MANIFEST)
            m = load(path)
            check_manifest(m)
            if argv[0] == "urls":
                for row in urls(m):
                    print("\t".join(str(x) for x in row))
        else:
            print(__doc__, file=sys.stderr)
            return 2
    except Refusal as r:
        print(f"windows-direct-publish: REFUSED — {r}", file=sys.stderr)
        return 1
    except FileNotFoundError as e:
        print(f"windows-direct-publish: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
