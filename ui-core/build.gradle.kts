// Three desktop tests read files OUTSIDE this module — `StringResourceFormatTest` scans every
// `composeResources/**/strings.xml` in the tree, `ErrorCopyParityTest` reads `tenshu-sdk-ios-core`'s
// `ErrorCopySurface.kt` — and Gradle cannot know that from the test classpath. Without these
// inputs an incremental `:ui-core:desktopTest` after editing another module's catalogue is
// UP-TO-DATE: observed 2026-09-12, the pre-fix Drive catalogue (`\"%1$s\"`) reported green until
// `--rerun`. `scripts/run-gate.sh` clears results and never saw this; this makes the per-module
// run honest too. `build/` and `node_modules/` are excluded so the walk stays cheap.
tasks.named<Test>("desktopTest") {
    inputs.files(
        fileTree(rootDir) {
            include("*/src/*/composeResources/**/strings.xml")
            include("tenshu-sdk-ios-core/src/iosMain/kotlin/org/tenshu/sdk/ios/ErrorCopySurface.kt")
            exclude("**/build/**", "**/node_modules/**", ".git/**", ".gradle/**")
        },
    ).withPropertyName("crossModuleCatalogues").withPathSensitivity(PathSensitivity.RELATIVE)
    // `PrivacyPolicyParityTest` reads the Swift and TypeScript copies of the policy-link rule and
    // the apex's page generator — the same blind spot, for the same reason.
    inputs.files(
        "$rootDir/ios-release/Sources/PrivacyPolicy.swift",
        "$rootDir/web/shared/legal.ts",
        "$rootDir/web/apex/support-pages/privacy.ts",
    ).withPropertyName("privacyPolicyCopies").withPathSensitivity(PathSensitivity.RELATIVE)
    // `ControlServerCheckTest` reads every desktop app's build file: Control's bundle id, and the
    // peer-gate JVM args each app must pass.
    inputs.files(fileTree(rootDir) { include("*-desktop/build.gradle.kts") })
        .withPropertyName("desktopBuildFiles").withPathSensitivity(PathSensitivity.RELATIVE)
}

