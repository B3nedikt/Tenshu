// --- Build-time store links for Control (ADR 0025 §Decision 6; see the generated ControlStoreConfig) ---
//
// Where another app sends a user who has no Control. Resolved at *build* time for the same reason
// `:control-shared-proxy` bakes the relay origin: Android has no runtime env / `-D` knob at all, and
// a packaged desktop app never sees one either. Precedence mirrors that task exactly — `-P<key>` →
// `$ENV` → `local.properties` (gitignored) — so there is one mechanism to learn.
//
// ⚠⚠ **The default is EMPTY, and that is the decision, not an oversight.** ADR 0022 §3 shipped a
// hardcoded `id000000000` App Store id, and the only way to discover it was broken was to tap it in
// production. Unset renders an honest "not on the store yet" instead, so shipping a *wrong* link now
// requires configuring a wrong one.
//
// ⚠ iOS is deliberately absent here: it already resolves this through
// `TENSHU_CONTROL_APP_STORE_ID` → Info.plist → `Control.appStoreURL` (ADR 0022 §3), and the Kotlin
// side reads that same Info.plist key. Generating a second iOS constant would give one platform two
// sources of truth, which is the thing 0022 §3 argued against.
fun localProperty(key: String): String? {
    val file = rootProject.file("local.properties")
    if (!file.exists()) return null
    val props = Properties().apply { file.inputStream().use { load(it) } }
    return props.getProperty(key)?.takeIf { it.isNotBlank() }
}

fun resolveStoreLink(key: String, env: String): String =
    (findProperty(key) as String?)?.takeIf { it.isNotBlank() }
        ?: System.getenv(env)?.takeIf { it.isNotBlank() }
        ?: localProperty(key)
        ?: ""

/**
 * Escapes a configured value for a generated Kotlin `"…"` literal (`\`, `"`, `$`). ⚠ Applied at
 * configuration time: a script function called from a task action breaks the configuration cache.
 */
fun kotlinStringBody(value: String): String =
    value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

val controlPlayUrl: String = resolveStoreLink("tenshu.control.playUrl", "TENSHU_CONTROL_PLAY_URL")
val controlMacAppStoreUrl: String =
    resolveStoreLink("tenshu.control.macAppStoreUrl", "TENSHU_CONTROL_MAC_APP_STORE_URL")

// ⚠ Each app's own Play listing, for the skew fence's **Update** button on a Play copy
// (`core-schema-skew-surface.md` §8.5). Same keys, one per app: `tenshu.<app>.playUrl` /
// `TENSHU_<APP>_PLAY_URL`. Empty = unconfigured = no button, never a dead link. Control's is the
// `controlPlayUrl` above, so its Get and Update links cannot disagree.
val firstPartyAndroidApps = listOf(
    "control", "drive", "photos", "maps", "timeline", "fit", "calendar", "contacts", "home", "mia",
)
val appPlayUrls: Map<String, String> = firstPartyAndroidApps.associateWith { app ->
    if (app == "control") controlPlayUrl
    else resolveStoreLink("tenshu.$app.playUrl", "TENSHU_${app.uppercase()}_PLAY_URL")
}.filterValues { it.isNotBlank() }.mapValues { (_, url) -> kotlinStringBody(url) }

val controlStoreConfigDir = layout.buildDirectory.dir("generated/controlStoreConfig")
val generateControlStoreConfig = tasks.register("generateControlStoreConfig") {
    val outDir = controlStoreConfigDir
    val playUrl = controlPlayUrl
    val macAppStoreUrl = controlMacAppStoreUrl
    inputs.property("playUrl", playUrl)
    inputs.property("macAppStoreUrl", macAppStoreUrl)
    val playUrls = appPlayUrls
    inputs.property("appPlayUrls", playUrls.toSortedMap().toString())
    outputs.dir(outDir)
    doLast {
        val pkgDir = outDir.get().dir("app/tenshu/ui/storage").asFile
        pkgDir.mkdirs()
        val playUrlEntries = playUrls.toSortedMap().entries.joinToString("") { (app, url) ->
            "\n                    \"" + app + "\" to \"" + url + "\","
        }
        pkgDir.resolve("ControlStoreConfig.kt").writeText(
            """
            package app.tenshu.ui.storage

            /**
             * Build-time store links for Tenshu Control. GENERATED by the `generateControlStoreConfig`
             * Gradle task — do not edit by hand. Precedence: `-P<key>` → `${'$'}ENV` →
             * `local.properties` (gitignored) → **empty**.
             *
             * ⚠⚠ Empty means *no link configured*, and every caller must render that as a state
             * rather than an empty URL. See `ControlInstallRoute`.
             *
             * ⚠ A configured link is **necessary, not sufficient**: both platforms additionally
             * check that *this* build was actually installed from that store, so a sideloaded or
             * Homebrew copy is never sent to a store it did not come from.
             *
             * Set for a store build with `tenshu.control.playUrl=…` /
             * `tenshu.control.macAppStoreUrl=…` in `local.properties`, `-P`, or the environment.
             */
            internal object ControlStoreConfig {
                const val PLAY_URL: String = "$playUrl"
                const val MAC_APP_STORE_URL: String = "$macAppStoreUrl"

                /**
                 * Each first-party app's Play listing, by app name (`drive`, `control`, …), for the
                 * skew fence's Update button on a Play copy. Only configured apps appear; a missing
                 * app has no button. Set with `tenshu.<app>.playUrl=…`.
                 */
                val APP_PLAY_URLS: Map<String, String> = mapOf($playUrlEntries
                )
            }

            """.trimIndent() + "\n"
        )
    }
}

// --- The client side of the desktop IPC gate (threat model A14; desktop-ipc-client-identity.md §11) ---
//
// Every desktop app checks that the process serving `ipc.sock` is Tenshu Control signed by one of
// our teams. The team set is compiled in from the same value the build signs with, exactly as
// `:control-desktop`'s `generatePeerTrustAnchor` does for the server side. ⚠ Never a runtime
// property or env var: the check exists to stop a hostile local process, which could set those.
// Extra teams during a team migration: `tenshu.additionalTeamIds` (comma-separated).
val clientTeamIds: List<String> = buildSet {
    ((findProperty("tenshu.teamId") as String?)?.takeIf { it.isNotBlank() }
        ?: System.getenv("TENSHU_TEAM_ID")?.takeIf { it.isNotBlank() }
        ?: localProperty("tenshu.teamId"))?.let { add(it.trim()) }
    ((findProperty("tenshu.additionalTeamIds") as String?) ?: System.getenv("TENSHU_ADDITIONAL_TEAM_IDS"))
        ?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }?.let { addAll(it) }
}.sorted()

val clientPeerTrustDir = layout.buildDirectory.dir("generated/clientPeerTrust")
val generateClientPeerTrust = tasks.register("generateClientPeerTrust") {
    val outDir = clientPeerTrustDir
    val teams = clientTeamIds
    inputs.property("teamIds", teams.joinToString(","))
    outputs.dir(outDir)
    doLast {
        val pkgDir = outDir.get().dir("app/tenshu/ui/ipc").asFile
        pkgDir.mkdirs()
        val literal = teams.joinToString(", ") { "\"" + it + "\"" }
        pkgDir.resolve("ClientPeerTrust.kt").writeText(
            """
            package app.tenshu.ui.ipc

            /**
             * GENERATED by the `generateClientPeerTrust` Gradle task in ui-core — do not edit. The teams
             * whose signature on Tenshu Control this app accepts (`ControlServerCheck`). Empty when the
             * build has no Team ID, in which case no Control can attest and only developer mode connects.
             */
            internal object ClientPeerTrust {
                val FIRST_PARTY_TEAM_IDS: Set<String> = setOf($literal)
            }

            """.trimIndent() + "\n"
        )
    }
}

