// ADR 0016: per-module CMP resource catalogues. Pinning the generated
// `Res` accessor package lets call sites use a predictable
// `import app.tenshu.control.shared.resources.Res` regardless of how the
// plugin defaults change. Strings live in
// `commonMain/composeResources/values/strings.xml`.
compose.resources {
    packageOfResClass = "app.tenshu.control.shared.resources"
    generateResClass = always
}

// `PairingSasVersionHintParityTest` reads catalogues OUTSIDE this module — `control-ios`'s
// `PairingView.swift` and the web apex locale JSONs — which Gradle cannot see from the test
// classpath. Without these inputs an incremental `:control-shared:desktopTest` after editing one
// of them would be UP-TO-DATE (as `:ui-core`'s `ErrorCopyParityTest` would).
tasks.named<Test>("desktopTest") {
    inputs.files(
        "$rootDir/control-ios/Sources/PairingView.swift",
        "$rootDir/web/apex/locales/en/onboarding.json",
        "$rootDir/web/apex/locales/en/control.json",
    ).withPropertyName("pairingSasVersionHintCatalogues").withPathSensitivity(PathSensitivity.RELATIVE)
}
