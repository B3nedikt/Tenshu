// --- Which rail an Android build sells through (commerce-store-link-out.md D2/D3) ---
//
// `play` (the default) sells through Play Billing; `stripe` is for an APK distributed outside Play,
// which must work without Google Play services. A build fact, generated at build time like
// `:ui-core`'s store links: Android has no runtime knob, and a Play build must never offer Stripe.
//   ./gradlew :control:assembleRelease -Ptenshu.android.billingRail=stripe
val androidBillingRail: String = (findProperty("tenshu.android.billingRail") as String?)?.trim()
    ?.takeIf { it.isNotEmpty() } ?: "play"
require(androidBillingRail in setOf("play", "stripe")) {
    "tenshu.android.billingRail must be 'play' or 'stripe', got '$androidBillingRail'"
}
val billingRailConfigDir = layout.buildDirectory.dir("generated/billingRailConfig")
val generateBillingRailConfig = tasks.register("generateBillingRailConfig") {
    val outDir = billingRailConfigDir
    val rail = androidBillingRail
    inputs.property("rail", rail)
    outputs.dir(outDir)
    doLast {
        val pkgDir = outDir.get().dir("app/tenshu/control/ui").asFile
        pkgDir.mkdirs()
        val constant = if (rail == "stripe") "STRIPE" else "GOOGLE_PLAY"
        pkgDir.resolve("BillingRailConfig.kt").writeText(
            "package app.tenshu.control.ui\n\n" +
                "import app.tenshu.control.data.BillingRail\n\n" +
                "/** GENERATED by `generateBillingRailConfig` from `-Ptenshu.android.billingRail`. Do not edit. */\n" +
                "internal val ANDROID_BILLING_RAIL: BillingRail = BillingRail.$constant\n",
        )
    }
}

