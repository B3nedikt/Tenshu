// --- Build-time proxy config (relay + commerce origins; see the generated RelayConfig) ---
// Android has no runtime env / `-D` knob at all, iOS has one only in a debug binary, and desktop
// has one that a packaged app never sees — so the relay origin, the commerce origin, and the
// billing-mock default are resolved at *build* time and generated into a `RelayConfig` constant
// that **all three** platform `PlatformProxyModule`s read as their final fallback. Precedence for each: `-P<key>` → `$ENV` →
// `local.properties` (gitignored) → the production default. So an un-configured build hits the
// real relay + real commerce; point at a local stack with
// `tenshu.relayUrl=http://10.0.2.2:8080`, `tenshu.commerceUrl=http://10.0.2.2:8081`,
// `tenshu.billingMock=false` in `local.properties` (`10.0.2.2` = the emulator's host loopback;
// use `localhost` for the iOS simulator) — nothing in git.
//
// ⚠⚠ Every platform's origins must come from here. A hardcoded fallback in a platform module
// ships as-is: a release iPhone build has no env knob to correct it with, so a loopback default
// sends the OTP call to an address that answers nothing.
fun localProperty(key: String): String? {
    val file = rootProject.file("local.properties")
    if (!file.exists()) return null
    val props = Properties().apply { file.inputStream().use { load(it) } }
    return props.getProperty(key)?.takeIf { it.isNotBlank() }
}

// Precedence for each origin: `-P<key>` → `$ENV` → `local.properties` (gitignored) → prod default.
fun resolveProxyOrigin(key: String, env: String, default: String): String =
    (findProperty(key) as String?)?.takeIf { it.isNotBlank() }
        ?: System.getenv(env)?.takeIf { it.isNotBlank() }
        ?: localProperty(key)
        ?: default

val proxyRelayUrl: String =
    resolveProxyOrigin("tenshu.relayUrl", "TENSHU_RELAY_URL", "https://relay.tenshu.app")

// Commerce origin + billing-mock default, baked the same way — the runtime
// `System.getenv`/`getProperty` reads in androidMain never fire on a device, and the iosMain
// `NSProcessInfo` read is debug-only, so on both platforms these are the real fallback. Default
// commerce = the production issuer, mirroring the relay default, so an un-configured release build
// hits real commerce. billingMock only matters in a debug build (a release build always uses real
// commerce via the dev-key guard); default true keeps a plain debug build on the in-process
// dev-seed minter.
val proxyCommerceUrl: String =
    resolveProxyOrigin("tenshu.commerceUrl", "TENSHU_COMMERCE_URL", "https://commerce.service.tenshu.app")
val proxyBillingMock: Boolean =
    resolveProxyOrigin("tenshu.billingMock", "TENSHU_BILLING_MOCK", "true").toBooleanStrictOrNull() ?: true

val relayConfigDir = layout.buildDirectory.dir("generated/relayConfig/proxy")
val generateProxyRelayConfig = tasks.register("generateProxyRelayConfig") {
    val outDir = relayConfigDir
    val relayUrl = proxyRelayUrl
    val commerceUrl = proxyCommerceUrl
    val billingMock = proxyBillingMock
    inputs.property("relayUrl", relayUrl)
    inputs.property("commerceUrl", commerceUrl)
    inputs.property("billingMock", billingMock)
    outputs.dir(outDir)
    doLast {
        val pkgDir = outDir.get().dir("app/tenshu/control/proxy").asFile
        pkgDir.mkdirs()
        pkgDir.resolve("RelayConfig.kt").writeText(
            """
            package app.tenshu.control.proxy

            /**
             * Build-time proxy origins for the Android and iOS builds (relay + commerce) plus
             * the billing-mock default. GENERATED by the `generateProxyRelayConfig` Gradle task —
             * do not edit by hand. Android has no runtime env / `-D` knob at all (the
             * `System.getenv` / `getProperty` reads in `PlatformProxyModule` never fire on a
             * device) and iOS honours `NSProcessInfo` only in a debug binary, so these are baked at
             * build time. Precedence for each: `-P<key>` → `${'$'}ENV` → `local.properties`
             * (gitignored) → the production default. Override for a local stack in
             * `local.properties`: `tenshu.relayUrl=http://10.0.2.2:8080`,
             * `tenshu.commerceUrl=http://10.0.2.2:8081`, `tenshu.billingMock=false`
             * (`10.0.2.2` = the Android emulator's host loopback; the iOS simulator uses
             * `localhost`).
             *
             * ⚠ `RELAY_URL` is read by androidMain only — iosMain and desktopMain both bind
             * `syncRelayUrl` directly (iOS carries its own debug-only `TENSHU_DEV_RELAY`
             * override, `DevRelayOverride`). Only `COMMERCE_URL` / `BILLING_MOCK` are shared
             * across all three.
             */
            internal object RelayConfig {
                const val RELAY_URL: String = "$relayUrl"
                const val COMMERCE_URL: String = "$commerceUrl"
                const val BILLING_MOCK: Boolean = $billingMock
            }

            """.trimIndent() + "\n"
        )
    }
}

